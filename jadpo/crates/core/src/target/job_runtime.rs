//! Explicit host entrypoints for statically checked delivery schedules.
//! Hosts own wakeups and must provide both bounded runtime profiles.
use super::{line, ts_string, TargetGenerator};

impl TargetGenerator<'_> {
    pub(super) fn scheduled_jobs_target(&self) -> String {
        let bindings = self.project.delivery_model().bindings();
        let mut output = String::new();
        line(&mut output, "// Generated by Jadpo 0.0.1. Do not edit.");
        line(
            &mut output,
            "// Host-invoked only: the host owns wakeups and supplies the operation-time snapshot.",
        );
        line(
            &mut output,
            "import { authenticationHost, runDeliveryScheduleActivation } from \"./app.ts\";",
        );
        line(&mut output, "");
        line(
            &mut output,
            "export type ScheduledJobProfile = Readonly<{ executionMs: number; leaseMs: number }>;",
        );
        line(&mut output, "export const scheduledJobs = Object.freeze([");
        for binding in bindings {
            let schedule = binding.schedule();
            line(
                &mut output,
                &format!(
                    "  Object.freeze({{ name: {}, intervalMs: {}, concurrency: \"singleton\", retryWakeup: \"next_schedule\" }}),",
                    ts_string(&schedule.job),
                    schedule.interval_ms,
                ),
            );
        }
        line(&mut output, "] as const);");
        line(
            &mut output,
            "export type ScheduledJobName = (typeof scheduledJobs)[number][\"name\"];",
        );
        line(&mut output, "");
        line(&mut output, "export async function runScheduledJob(name: ScheduledJobName, workerCredential: string, activationProfile: ScheduledJobProfile, deliveryProfile: ScheduledJobProfile, operationTime: string) {");
        line(&mut output, "  if (operationTime === undefined) throw new TypeError(\"operationTime is required\");");
        line(&mut output, "  switch (name) {");
        for binding in bindings {
            let strategy = binding
                .descriptor()
                .authority
                .validator
                .path
                .first()
                .expect("checked delivery authority names its credential strategy");
            line(
                &mut output,
                &format!("    case {}: {{", ts_string(&binding.schedule().job)),
            );
            line(&mut output, &format!("      const proof = await authenticationHost().prepareDeliveryCredential({}, workerCredential, Date.now());", ts_string(&strategy.text)));
            line(&mut output, &format!("      return runDeliveryScheduleActivation({}, proof, activationProfile, deliveryProfile, operationTime);", ts_string(binding.binding_identity())));
            line(&mut output, "    }");
        }
        line(
            &mut output,
            "    default: throw new Error(\"Unknown checked scheduled job\");",
        );
        line(&mut output, "  }");
        line(&mut output, "}");
        output
    }
}
