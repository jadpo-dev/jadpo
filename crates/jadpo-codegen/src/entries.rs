//! Each route's typed entry (docs/compiler-runtime.md §2.5, "A typed
//! per-route entry"; roadmap chunk 8.1p): a project's `entries` module,
//! holding a reader for each codec a route reads, a writer for each codec
//! it writes, and each route's [`Entry`](jadpo_runtime) by its number,
//! generated from the route table's codecs, shapes and validators.
//!
//! A reader walks a request's JSON in the codec's own order and calls
//! `jadpo_value::json::reading` for every rule, so the generated code is
//! the walk's structure alone: an object's members by name as literals,
//! in declared order, and the members it doesn't declare; a list's items;
//! a plain variant matched by its wire name, a payload variant by its
//! `tag`; a scalar read and checked by the runtime's one reader and the
//! program's validator by number. A writer writes the `Value` the action
//! or query gave, member names and wire names as literals. What isn't
//! walked here (a map, a standard type sent as its parts, a geometry, a
//! feature, a vector's float, a page, a standard enum read ignoring case,
//! a `Jwk`) is read and written by the codec walk at that point, and so
//! is a value that isn't the record, variant or list its type expects.

use std::collections::BTreeSet;

use jadpo_plan::Plan;
use jadpo_std::http::{Codec, CodecId, RoutePlan, Run, Segment};
use jadpo_std::types::ShapePlan;
use proc_macro2::{Ident, Literal, TokenStream};
use quote::{format_ident, quote};

use crate::body::number;

/// The tokens of a project's `entries` module.
pub(crate) fn module(plan: &Plan) -> TokenStream {
    let runtime = plan.runtime();
    let mut made = Made {
        codecs: &runtime.routes.codecs,
        shapes: &runtime.shapes,
        readers: BTreeSet::new(),
        texts: BTreeSet::new(),
        writers: BTreeSet::new(),
        inputs: BTreeSet::new(),
    };
    let mut statics = Vec::new();
    let mut arms = Vec::new();
    for (at, route) in runtime.routes.routes.iter().enumerate() {
        let Some(entry) = made.entry(route) else {
            continue;
        };
        let n = number(u32::try_from(at).unwrap_or(u32::MAX));
        let name = format_ident!("ROUTE_{}", at);
        let doc = Literal::string(&format!(" `{}`", route.label()));
        statics.push(quote! {
            #[doc = #doc]
            static #name: Entry = #entry;
        });
        arms.push(quote!(#n => Some(&#name),));
    }
    let functions = made.functions();
    quote! {
        #![doc = " Each route's typed entry, generated from its types' plans (docs/compiler-runtime.md §2.5, \"A typed per-route entry\"). Generated by Jadpo; don't edit it."]

        use jadpo_runtime::http::Entry;
        use jadpo_std::Builtin;
        use jadpo_std::http::CodecId;
        use jadpo_value::Value;
        use jadpo_value::json::reading::{At, Field, Got, Reading};
        use jadpo_value::json::{Codecs, Item, Kind, Members, write_scalar, write_string};

        /// Route `n`'s entry.
        pub(super) fn entry(n: u32) -> Option<&'static Entry> {
            match n {
                #(#arms)*
                _ => None,
            }
        }

        #(#statics)*

        #(#functions)*
    }
}

/// The codecs a project's entries read and write, gathered from its
/// routes before any function is written.
struct Made<'p> {
    codecs: &'p [Codec],
    shapes: &'p [ShapePlan],
    /// Codecs read from JSON: `r<n>`.
    readers: BTreeSet<u32>,
    /// Codecs read from a placeholder's text: `p<n>`.
    texts: BTreeSet<u32>,
    /// Codecs written as JSON: `w<n>`.
    writers: BTreeSet<u32>,
    /// Object codecs read as a route's whole input: `i<n>`.
    inputs: BTreeSet<u32>,
}

/// How a codec is walked.
enum Walk<'p> {
    /// `T?`.
    Nullable(u32),
    /// A scalar read by the runtime's one reader.
    Scalar {
        builtin: jadpo_std::Builtin,
        validator: u32,
        int_as_number: bool,
    },
    Object {
        shape: u32,
        plan: &'p ShapePlan,
        fields: &'p [CodecId],
        validator: Option<u32>,
    },
    Enum {
        ty: &'p str,
        variants: &'p [jadpo_std::http::VariantCodec],
    },
    List {
        item: u32,
        validator: u32,
        set: bool,
    },
    /// Read and written by the codec walk.
    Walked,
}

impl<'p> Made<'p> {
    fn codec(&self, id: u32) -> Option<&'p Codec> {
        self.codecs.get(id as usize)
    }

    /// Codec `id` as JSON reads and writes it outside a provider's wire:
    /// a provider's field that says how it is sent is its contract's
    /// codec everywhere else.
    fn contract(&self, id: u32) -> u32 {
        let mut id = id;
        for _ in 0..self.codecs.len() {
            match self.codec(id) {
                Some(Codec::Wired { contract, .. }) => id = contract.0,
                _ => break,
            }
        }
        id
    }

    /// How codec `id` is walked: a generated walk for what the codec walk
    /// does by the codec alone, and the codec walk itself for the rest.
    fn walk(&self, id: u32) -> Walk<'p> {
        match self.codec(id) {
            Some(Codec::Nullable(inner)) => Walk::Nullable(self.contract(inner.0)),
            Some(Codec::Scalar {
                builtin,
                validator,
                int_as_number,
            }) => {
                let parts = jadpo_std::standard::of_builtin(*builtin)
                    .is_some_and(|entry| matches!(entry.json, jadpo_std::standard::Json::Parts(_)));
                if parts {
                    Walk::Walked
                } else {
                    Walk::Scalar {
                        builtin: *builtin,
                        validator: validator.0,
                        int_as_number: *int_as_number,
                    }
                }
            }
            Some(Codec::Object {
                shape,
                fields,
                validator,
            }) => match self.shapes.get(shape.0 as usize) {
                // A `Jwk` ignores the members RFC 7517 lets a key set add.
                Some(plan)
                    if plan.ty != jadpo_std::standard::security::JWK
                        && plan.fields.len() == fields.len() =>
                {
                    Walk::Object {
                        shape: shape.0,
                        plan,
                        fields,
                        validator: validator.map(|validator| validator.0),
                    }
                }
                _ => Walk::Walked,
            },
            // A standard enum's code is read ignoring case (area 19).
            Some(Codec::Enum { ty, variants }) if jadpo_std::standard_type(ty).is_none() => {
                let shaped = variants.iter().all(|variant| {
                    variant.fields.as_ref().is_none_or(|(shape, fields)| {
                        self.shapes
                            .get(shape.0 as usize)
                            .is_some_and(|plan| plan.fields.len() == fields.len())
                    })
                });
                if shaped {
                    Walk::Enum { ty, variants }
                } else {
                    Walk::Walked
                }
            }
            Some(Codec::List { item, validator }) => Walk::List {
                item: self.contract(item.0),
                validator: validator.0,
                set: false,
            },
            Some(Codec::Set { item, validator }) => Walk::List {
                item: self.contract(item.0),
                validator: validator.0,
                set: true,
            },
            _ => Walk::Walked,
        }
    }

    /// Route `route`'s entry, gathering what it reads and writes; `None`
    /// for a route the runtime answers itself, or one with nothing to read
    /// or write.
    fn entry(&mut self, route: &RoutePlan) -> Option<TokenStream> {
        if !matches!(
            route.run,
            Run::Action(_) | Run::Query(_) | Run::Listing { .. }
        ) {
            return None;
        }
        let params: Vec<Ident> = route
            .segments
            .iter()
            .filter_map(|segment| match segment {
                Segment::Param { codec, .. } => Some(codec.0),
                Segment::Fixed(_) => None,
            })
            .map(|codec| {
                self.text(codec);
                format_ident!("p{}", codec)
            })
            .collect();
        let input = route.input.as_ref().and_then(|plan| {
            let id = self.contract(plan.codec.0);
            matches!(self.walk(id), Walk::Object { .. }).then(|| {
                self.inputs.insert(id);
                self.read(id);
                let input = format_ident!("i{}", id);
                quote!(Some(#input))
            })
        });
        let output = route.output.map(|codec| {
            let id = self.contract(codec.0);
            self.write(id);
            let output = format_ident!("w{}", id);
            quote!(Some(#output))
        });
        if params.is_empty() && input.is_none() && output.is_none() {
            return None;
        }
        let input = input.unwrap_or_else(|| quote!(None));
        let output = output.unwrap_or_else(|| quote!(None));
        Some(quote!(Entry {
            params: &[#(#params),*],
            input: #input,
            output: #output,
        }))
    }

    /// Codec `id` read from a placeholder's text, and what that reads.
    fn text(&mut self, id: u32) {
        if !self.texts.insert(id) {
            return;
        }
        match self.codec(id) {
            Some(Codec::Nullable(inner)) => self.text(inner.0),
            Some(Codec::Enum { .. }) if matches!(self.walk(id), Walk::Enum { .. }) => self.read(id),
            _ => {}
        }
    }

    /// Codec `id` read from JSON, and every codec it reads.
    fn read(&mut self, id: u32) {
        if !self.readers.insert(id) {
            return;
        }
        match self.walk(id) {
            Walk::Nullable(inner) => self.read(inner),
            Walk::Object { fields, .. } => {
                for field in fields {
                    self.read(self.contract(field.0));
                }
            }
            Walk::Enum { variants, .. } => {
                for variant in variants {
                    if let Some((_, fields)) = &variant.fields {
                        for field in fields {
                            self.read(self.contract(field.0));
                        }
                    }
                }
            }
            Walk::List { item, .. } => self.read(item),
            Walk::Scalar { .. } | Walk::Walked => {}
        }
    }

    /// Codec `id` written as JSON, and every codec it writes.
    fn write(&mut self, id: u32) {
        if !self.writers.insert(id) {
            return;
        }
        match self.walk(id) {
            Walk::Nullable(inner) => self.write(inner),
            Walk::Object { fields, .. } => {
                for field in fields {
                    self.write(self.contract(field.0));
                }
            }
            Walk::Enum { variants, .. } => {
                for variant in variants {
                    if let Some((_, fields)) = &variant.fields {
                        for field in fields {
                            self.write(self.contract(field.0));
                        }
                    }
                }
            }
            Walk::List { item, .. } => self.write(item),
            Walk::Scalar { .. } | Walk::Walked => {}
        }
    }

    /// Every function gathered, readers, then placeholders' readers,
    /// inputs and writers, each in codec order.
    fn functions(&self) -> Vec<TokenStream> {
        let mut out = Vec::new();
        for id in &self.readers {
            out.push(self.reader(*id));
        }
        for id in &self.texts {
            out.push(self.text_reader(*id));
        }
        for id in &self.inputs {
            let (input, object) = (format_ident!("i{}", id), format_ident!("o{}", id));
            let doc = Literal::string(&format!(" Codec {id} read as a route's input."));
            out.push(quote! {
                #[doc = #doc]
                fn #input(r: &mut Reading<'_>, m: &Members<'_>) -> Option<Value> {
                    #object(r, m, &At::Top)
                }
            });
        }
        for id in &self.writers {
            out.push(self.writer(*id));
        }
        out
    }

    /// `r<id>`: codec `id` read from an item at a place.
    fn reader(&self, id: u32) -> TokenStream {
        let name = format_ident!("r{}", id);
        let n = number(id);
        let doc = Literal::string(&format!(" Codec {id} read from JSON."));
        let body = match self.walk(id) {
            Walk::Nullable(inner) => {
                let inner = format_ident!("r{}", inner);
                quote! {
                    if item.is_null() {
                        return Some(Value::None);
                    }
                    #inner(r, item, at)
                }
            }
            Walk::Scalar {
                builtin, validator, ..
            } => {
                let builtin = builtin_tokens(builtin);
                let validator = number(validator);
                quote! {
                    if !r.given(item, at) {
                        return None;
                    }
                    r.scalar(#n, #builtin, #validator, item, at)
                }
            }
            Walk::Object {
                shape,
                plan,
                fields,
                validator,
            } => {
                let object = format_ident!("o{}", id);
                let walk = self.object_walk(shape, plan, fields, validator);
                return quote! {
                    #[doc = #doc]
                    fn #name(r: &mut Reading<'_>, item: Item<'_>, at: &At<'_>) -> Option<Value> {
                        if !r.given(item, at) {
                            return None;
                        }
                        let m = r.members(item, at)?;
                        #object(r, &m, at)
                    }

                    fn #object(r: &mut Reading<'_>, m: &Members<'_>, at: &At<'_>) -> Option<Value> {
                        #walk
                    }
                };
            }
            Walk::Enum { ty, variants } => self.enum_reader(ty, variants),
            Walk::List {
                item,
                validator,
                set,
            } => {
                let item = format_ident!("r{}", item);
                let validator = number(validator);
                quote! {
                    if !r.given(item, at) {
                        return None;
                    }
                    r.list(item, at, #item, #set, #validator)
                }
            }
            Walk::Walked => quote!(r.generic(#n, item, at)),
        };
        quote! {
            #[doc = #doc]
            fn #name(r: &mut Reading<'_>, item: Item<'_>, at: &At<'_>) -> Option<Value> {
                #body
            }
        }
    }

    /// An object's or a payload variant's fields read from `m`, the
    /// members of the object at `at`, in declared order, then the members
    /// it doesn't declare, then the value built by its shape and checked
    /// by `validator`.
    fn object_walk(
        &self,
        shape: u32,
        plan: &ShapePlan,
        fields: &[CodecId],
        validator: Option<u32>,
    ) -> TokenStream {
        let count = fields.len();
        let mut reads = Vec::new();
        let mut declared = Vec::new();
        for (slot, (field, codec)) in plan.fields.iter().zip(fields).enumerate() {
            let member = field.wire.clone().unwrap_or_else(|| {
                jadpo_std::standard::wire_name(&plan.ty, &field.name).to_string()
            });
            let raw = self.codec(codec.0);
            let nullable = matches!(raw, Some(Codec::Nullable(_)));
            let list = match raw {
                Some(Codec::Nullable(inner)) => matches!(
                    self.codec(inner.0),
                    Some(Codec::List { .. } | Codec::Set { .. })
                ),
                Some(Codec::List { .. } | Codec::Set { .. }) => true,
                _ => false,
            };
            let (absent, open_nullable, omittable) = (
                field.absent.is_some(),
                plan.open && nullable,
                field.omittable,
            );
            let reader = format_ident!("r{}", self.contract(codec.0));
            let slot = number(u32::try_from(slot).unwrap_or(u32::MAX));
            let name = Literal::string(&member);
            reads.push(quote! {
                let f = At::Member(at, #name);
                match r.field(m, #name, Field { absent: #absent, open_nullable: #open_nullable, omittable: #omittable, list: #list }, &f) {
                    Got::Read(item) => slots[#slot] = #reader(r, item, &f),
                    Got::None => slots[#slot] = Some(Value::None),
                    Got::Left => {}
                }
            });
            declared.push(name);
        }
        let unknown = if plan.open {
            TokenStream::new()
        } else {
            quote!(r.unknown(m, &[#(#declared),*], at);)
        };
        let nones = (0..count).map(|_| quote!(None));
        let shape = number(shape);
        let built = match validator {
            Some(validator) => {
                let validator = number(validator);
                quote! {
                    let value = r.build(#shape, &mut slots)?;
                    r.check(#validator, value, at)
                }
            }
            None => quote!(r.build(#shape, &mut slots)),
        };
        quote! {
            let before = r.count();
            let mut slots: [Option<Value>; #count] = [#(#nones),*];
            #(#reads)*
            #unknown
            if r.count() > before {
                return None;
            }
            #built
        }
    }

    /// An enum read from a string naming a plain variant by its wire
    /// name, or from an object naming a variant in `tag`, its payload's
    /// fields the object's other members.
    fn enum_reader(&self, ty: &str, variants: &[jadpo_std::http::VariantCodec]) -> TokenStream {
        let ty_text = Literal::string(ty);
        // A plain variant by its wire name, the first that has it.
        let mut named = BTreeSet::new();
        let mut plain = Vec::new();
        for variant in variants.iter().filter(|variant| variant.fields.is_none()) {
            if !named.insert(variant.wire.as_str()) {
                continue;
            }
            let (wire, name) = (
                Literal::string(&variant.wire),
                Literal::string(&variant.name),
            );
            let ordinal = number(variant.ordinal);
            plain.push(
                quote!(#wire => Some(Value::variant(#ty_text, #ordinal, #name, Vec::new())),),
            );
        }
        // Any variant by its wire name or its name in `tag`, the first that
        // has either.
        let mut tagged = BTreeSet::new();
        let mut tags = Vec::new();
        for variant in variants {
            let spellings: Vec<Literal> = [variant.wire.as_str(), variant.name.as_str()]
                .into_iter()
                .collect::<BTreeSet<&str>>()
                .into_iter()
                .filter(|spelling| tagged.insert(spelling.to_string()))
                .map(Literal::string)
                .collect();
            if spellings.is_empty() {
                continue;
            }
            let body = match &variant.fields {
                None => quote! {
                    r.problem(at, "type");
                    None
                },
                Some((shape, fields)) => match self.shapes.get(shape.0 as usize) {
                    Some(plan) => {
                        let walk = self.object_walk(shape.0, plan, fields, None);
                        quote! {
                            let m = &m.untagged();
                            #walk
                        }
                    }
                    None => quote!(None),
                },
            };
            tags.push(quote!(#(#spellings)|* => { #body }));
        }
        quote! {
            if !r.given(item, at) {
                return None;
            }
            match item.kind() {
                Kind::String => {
                    let name = item.text()?;
                    match &*name {
                        #(#plain)*
                        _ => {
                            r.problem(at, "variant");
                            None
                        }
                    }
                }
                Kind::Object => {
                    let m = item.members()?;
                    let tag = r.tag(&m, at)?;
                    match &*tag {
                        #(#tags)*
                        _ => {
                            r.problem(&At::Member(at, "tag"), "variant");
                            None
                        }
                    }
                }
                _ => {
                    r.problem(at, "type");
                    None
                }
            }
        }
    }

    /// `p<id>`: codec `id` read from a placeholder's text, as the codec
    /// walk's `read_text` reads it.
    fn text_reader(&self, id: u32) -> TokenStream {
        let name = format_ident!("p{}", id);
        let n = number(id);
        let doc = Literal::string(&format!(" Codec {id} read from a placeholder's text."));
        let body = match self.codec(id) {
            Some(Codec::Nullable(inner)) => {
                let inner = format_ident!("p{}", inner.0);
                quote!(#inner(r, text, at))
            }
            Some(Codec::Scalar {
                builtin, validator, ..
            }) => {
                let builtin = builtin_tokens(*builtin);
                let validator = number(validator.0);
                quote!(r.text(#builtin, #validator, text, at))
            }
            Some(Codec::Enum { .. }) if matches!(self.walk(id), Walk::Enum { .. }) => {
                let reader = format_ident!("r{}", id);
                quote!(#reader(r, Item::Text(text), at))
            }
            _ => quote!(r.generic_text(#n, text, at)),
        };
        quote! {
            #[doc = #doc]
            fn #name(r: &mut Reading<'_>, text: &str, at: &At<'_>) -> Option<Value> {
                #body
            }
        }
    }

    /// `w<id>`: a value of codec `id` written as JSON.
    fn writer(&self, id: u32) -> TokenStream {
        let name = format_ident!("w{}", id);
        let n = number(id);
        let doc = Literal::string(&format!(" Codec {id} written as JSON."));
        let walked = quote!(c.write(CodecId(#n), v, out));
        let body = match self.walk(id) {
            Walk::Nullable(inner) => {
                let inner = format_ident!("w{}", inner);
                quote!(#inner(c, v, out))
            }
            Walk::Scalar { int_as_number, .. } => quote!(write_scalar(v, #int_as_number, out)),
            Walk::Object { plan, fields, .. } => self.object_writer(id, plan, fields),
            Walk::Enum { variants, .. } => self.enum_writer(id, variants),
            Walk::List { item, .. } => {
                let item = format_ident!("w{}", item);
                quote! {
                    if matches!(v, Value::None | Value::Unit) {
                        out.push_str("null");
                        return;
                    }
                    out.push('[');
                    for (at, entry) in v.items().unwrap_or_default().iter().enumerate() {
                        if at > 0 {
                            out.push(',');
                        }
                        #item(c, entry, out);
                    }
                    out.push(']');
                }
            }
            Walk::Walked => walked,
        };
        quote! {
            #[doc = #doc]
            fn #name(c: &Codecs<'_>, v: &Value, out: &mut String) {
                #body
            }
        }
    }

    /// A record of the object's own type with one value per field, its
    /// members in declared order; anything else by the codec walk.
    fn object_writer(&self, id: u32, plan: &ShapePlan, fields: &[CodecId]) -> TokenStream {
        let n = number(id);
        let ty = Literal::string(&plan.ty);
        // A standard problem's members that are `none` are left out, as
        // RFC 9457 sends them (chunk 5.5n).
        let members = jadpo_std::standard_type(&plan.ty)
            .is_some_and(|entry| matches!(entry.json, jadpo_std::standard::Json::Members(_)));
        let values: Vec<Ident> = (0..fields.len())
            .map(|at| format_ident!("f{}", at))
            .collect();
        let mut writes = Vec::new();
        for (at, ((field, codec), value)) in plan.fields.iter().zip(fields).zip(&values).enumerate()
        {
            let member = field.wire.clone().unwrap_or_else(|| {
                jadpo_std::standard::wire_name(&plan.ty, &field.name).to_string()
            });
            let written = member_name(&member);
            let writer = format_ident!("w{}", self.contract(codec.0));
            let place = number(u32::try_from(at).unwrap_or(u32::MAX));
            let left_out = if members {
                quote!(omitted.contains(&#place) || *#value == Value::None)
            } else {
                quote!(omitted.contains(&#place))
            };
            writes.push(quote! {
                if !(#left_out) {
                    if !first {
                        out.push(',');
                    }
                    first = false;
                    #written
                    #writer(c, #value, out);
                }
            });
        }
        quote! {
            let Value::Record(record) = v else {
                return c.write(CodecId(#n), v, out);
            };
            let [#((_, #values)),*] = record.fields.as_slice() else {
                return c.write(CodecId(#n), v, out);
            };
            if &*record.ty != #ty {
                return c.write(CodecId(#n), v, out);
            }
            let omitted = record.omitted.as_deref().unwrap_or(&[]);
            let mut first = true;
            out.push('{');
            #(#writes)*
            out.push('}');
        }
    }

    /// A variant by its name: a plain one's wire name, a payload one's
    /// `tag` and fields; anything else by the codec walk.
    fn enum_writer(&self, id: u32, variants: &[jadpo_std::http::VariantCodec]) -> TokenStream {
        let n = number(id);
        let mut named = BTreeSet::new();
        let mut arms = Vec::new();
        for variant in variants {
            if !named.insert(variant.name.as_str()) {
                continue;
            }
            let name = Literal::string(&variant.name);
            let body = match &variant.fields {
                None => string_literal(&variant.wire),
                Some((shape, codecs)) => {
                    let Some(plan) = self.shapes.get(shape.0 as usize) else {
                        continue;
                    };
                    let values: Vec<Ident> = (0..codecs.len())
                        .map(|at| format_ident!("f{}", at))
                        .collect();
                    let tag = format!("{{\"tag\":{}", json_string(&variant.wire));
                    let opening = written_text(&tag, &variant.wire);
                    let fields = plan.fields.iter().zip(codecs).zip(&values).map(
                        |((field, codec), value)| {
                            let member = field.wire.clone().unwrap_or_else(|| {
                                jadpo_std::standard::wire_name(&plan.ty, &field.name).to_string()
                            });
                            let written = member_name(&member);
                            let writer = format_ident!("w{}", self.contract(codec.0));
                            quote! {
                                out.push(',');
                                #written
                                #writer(c, #value, out);
                            }
                        },
                    );
                    quote! {
                        let [#((_, #values)),*] = variant.fields.as_slice() else {
                            return c.write(CodecId(#n), v, out);
                        };
                        #opening
                        #(#fields)*
                        out.push('}');
                    }
                }
            };
            arms.push(quote!(#name => { #body }));
        }
        quote! {
            let Value::Variant(variant) = v else {
                return c.write(CodecId(#n), v, out);
            };
            match &*variant.name {
                #(#arms)*
                _ => c.write(CodecId(#n), v, out),
            }
        }
    }
}

/// `builtin` as generated code names it: `Builtin::Text`.
fn builtin_tokens(builtin: jadpo_std::Builtin) -> TokenStream {
    let variant = format_ident!("{}", format!("{builtin:?}"));
    quote!(Builtin::#variant)
}

/// Whether `text` is written in JSON as itself between quotes: printable
/// ASCII but `"` and `\`.
fn plain(text: &str) -> bool {
    text.bytes()
        .all(|byte| (b' '..=b'~').contains(&byte) && byte != b'"' && byte != b'\\')
}

/// `text` as a JSON string, for one [`plain`] says is written as itself.
fn json_string(text: &str) -> String {
    format!("\"{text}\"")
}

/// What writes a member's name and its colon.
fn member_name(member: &str) -> TokenStream {
    if plain(member) {
        let written = Literal::string(&format!("{}:", json_string(member)));
        quote!(out.push_str(#written);)
    } else {
        let member = Literal::string(member);
        quote! {
            write_string(#member, out);
            out.push(':');
        }
    }
}

/// What writes `text` as a JSON string.
fn string_literal(text: &str) -> TokenStream {
    if plain(text) {
        let written = Literal::string(&json_string(text));
        quote!(out.push_str(#written);)
    } else {
        let text = Literal::string(text);
        quote!(write_string(#text, out);)
    }
}

/// What writes `written`, the JSON text of a payload variant's opening
/// with `wire` its tag: as it is when the tag is [`plain`], otherwise its
/// tag through `write_string`.
fn written_text(written: &str, wire: &str) -> TokenStream {
    if plain(wire) {
        let written = Literal::string(written);
        quote!(out.push_str(#written);)
    } else {
        let wire = Literal::string(wire);
        quote! {
            out.push_str("{\"tag\":");
            write_string(#wire, out);
        }
    }
}
