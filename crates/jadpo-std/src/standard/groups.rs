/// The group standard type `name` is listed in.
pub fn group_of(name: &str) -> Option<&'static str> {
    GROUPS
        .iter()
        .find(|(_, names)| names.contains(&name))
        .map(|(group, _)| *group)
}

#[cfg(test)]
mod tests {
    use super::GROUPS;
    use crate::standard::STANDARD_TYPES;

    #[test]
    fn every_standard_type_is_in_exactly_one_group() {
        for entry in STANDARD_TYPES {
            let holding: Vec<&str> = GROUPS
                .iter()
                .filter(|(_, names)| names.contains(&entry.name))
                .map(|(group, _)| *group)
                .collect();
            assert_eq!(holding.len(), 1, "{} is in {holding:?}", entry.name);
        }
        let listed: usize = GROUPS.iter().map(|(_, names)| names.len()).sum();
        assert_eq!(
            listed,
            STANDARD_TYPES.len(),
            "a group lists a name that isn't a standard type"
        );
    }
}
