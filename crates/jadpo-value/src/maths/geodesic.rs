//! Geodesics on the WGS84 ellipsoid (area 20, "Operations" and "Precision
//! and determinism"): the inverse problem, the distance and the azimuths
//! between two points and the area between their geodesic and the
//! equator, and a ring's area from those, by C. F. F. Karney's methods
//! ("Algorithms for geodesics", J. Geodesy 87, 43–55, 2013), as
//! GeographicLib implements them, which PostGIS's `geography` uses.
//!
//! Every value is a [`Real`], fixed point at 2⁻¹³⁶, never a float, so
//! the interpreter, native builds and wasm32 give the same digits. The
//! series in the third flattening `n` and in `ε` are to the eighth order,
//! GeographicLib's highest: the terms left out are below `ε⁹ ≈ 10⁻²⁵`
