/// Newton's iterations before falling back on bisection, GeographicLib's
/// `maxit1_`.
const NEWTON: u32 = 20;
/// The iterations after which the result stands: `maxit1_` plus the bits
/// a working value holds plus 10, as GeographicLib's `maxit2_`.
const LAST: u32 = NEWTON + FRACTION + 10;

/// WGS84 (NIMA TR8350.2): the equatorial radius in metres and the
/// inverse flattening, both exact by definition.
const RADIUS: i64 = 6_378_137;
const INVERSE_FLATTENING: (i64, i64) = (298_257_223_563, 1_000_000_000);

/// The ellipsoid's constants and the series' coefficients in `ε`, worked
/// out once.
struct Ellipsoid {
    unit: Unit,
    a: Real,
    f: Real,
    f1: Real,
    e2: Real,
    ep2: Real,
    n: Real,
    b: Real,
    /// The authalic radius squared.
    c2: Real,
    /// π/180.
    degree: Real,
    a3x: Vec<Real>,
    c3x: Vec<Real>,
    c4x: Vec<Real>,
    tol0: Real,
    tol1: Real,
    tol2: Real,
    tolb: Real,
    xthresh: Real,
    etol2: Real,
}

fn wgs84() -> &'static Ellipsoid {
    static WGS84: OnceLock<Ellipsoid> = OnceLock::new();
    WGS84.get_or_init(Ellipsoid::wgs84)
}

impl Ellipsoid {
    fn wgs84() -> Ellipsoid {
        let unit = Unit::new();
        let one = unit.int(1);
        let a = unit.int(RADIUS);
        let f = unit.ratio(INVERSE_FLATTENING.1, INVERSE_FLATTENING.0);
        let f1 = one.sub(&f);
        let e2 = unit.mul(&f, &one.times(2).sub(&f));
        let ep2 = unit.div(&e2, &unit.sq(&f1));
        let n = unit.div(&f, &one.times(2).sub(&f));
        let b = unit.mul(&a, &f1);
        // c² = (a² + b² atanh(e) / e) / 2, atanh(e) / e by its series
        // 1 + e²/3 + e⁴/5 + ..., e² below 0.007.
        let mut power = one;
        let mut series = one;
        let mut odd = 3;
        loop {
            power = unit.mul(&power, &e2);
            let term = power.div_whole(odd);
            if term.is_zero() {
                break;
            }
            series = series.add(&term);
            odd += 2;
        }
        let c2 = unit
            .sq(&a)
            .add(&unit.mul(&unit.sq(&b), &series))
            .div_whole(2);
        let degree = unit.pi().div_whole(180);
        let mut a3x = Vec::with_capacity(ORDER);
        let mut o = 0;
        for j in (0..ORDER).rev() {
            let m = (ORDER - j - 1).min(j);
            a3x.push(coefficient(&unit, &A3, o, m, &n));
            o += m + 2;
        }
        let mut c3x = Vec::new();
        let mut o = 0;
        for l in 1..ORDER {
            for j in (l..ORDER).rev() {
                let m = (ORDER - j - 1).min(j);
                c3x.push(coefficient(&unit, &C3, o, m, &n));
                o += m + 2;
            }
        }
        let mut c4x = Vec::new();
        let mut o = 0;
        for l in 0..ORDER {
            for j in (l..ORDER).rev() {
                let m = ORDER - j - 1;
                c4x.push(coefficient(&unit, &C4, o, m, &n));
                o += m + 2;
            }
        }
        // GeographicLib's tolerances, from a machine epsilon: here 10⁴
        // units of the last place, about 10⁻³⁷, past the noise of a few
        // hundred truncations in λ₁₂.
        let tol0 = Real::tiny().times(10_000);
        let tol2 = unit.sqrt(&tol0);
        let tol1 = tol0.times(200);
        let tolb = tol0;
        let xthresh = tol2.times(1000);
        // 0.1 tol2 / √(max(0.001, |f|) min(1, 1 - f/2) / 2).
        let spread = unit.sqrt(&unit.mul(&f, &one.sub(&f.div_whole(2))).div_whole(2));
        let etol2 = unit.div(&tol2.div_whole(10), &spread);
        Ellipsoid {
            unit,
            a,
            f,
            f1,
            e2,
            ep2,
            n,
            b,
            c2,
            degree,
            a3x,
            c3x,
            c4x,
            tol0,
            tol1,
            tol2,
            tolb,
            xthresh,
            etol2,
        }
    }

    fn one(&self) -> Real {
        self.unit.int(1)
    }

    /// The sine and cosine of `x` degrees, `x` brought exactly to within
    /// 45° of 0 by whole quarter turns first, as GeographicLib's
    /// `sincosd`, so a multiple of 90° gives 0 and ±1 exactly.
    fn sin_cos_degrees(&self, x: &Real) -> (Real, Real) {
        let u = &self.unit;
        let ninety = u.int(90);
        let forty_five = u.int(45);
        // The nearest whole number of quarter turns, ties to even, as
        // `remquo` gives it.
        let mut r = *x;
        let mut turns: i64 = 0;
        if !x.is_zero() {
            let k = u.div(x, &ninety);
            let whole = k.rounded(0, jadpo_std::Rounding::HalfEven).unwrap_or(0);
            turns = i64::try_from(whole).unwrap_or(0);
            r = x.sub(&ninety.times(turns));
            // A quotient cut a unit short of a tie can leave r just past
            // 45°: one more quarter turn brings it back.
            if r > forty_five {
                r = r.sub(&ninety);
                turns += 1;
            } else if r < forty_five.neg() {
                r = r.add(&ninety);
                turns -= 1;
            }
        }
        let size = r.abs();
        let (s, c) = if size == forty_five {
            let c = u.sqrt(&u.ratio(1, 2));
            (if r.is_negative() { c.neg() } else { c }, c)
        } else if size == u.int(30) {
            let half = u.ratio(1, 2);
            (
                if r.is_negative() { half.neg() } else { half },
                u.sqrt(&u.int(3)).div_whole(2),
            )
        } else {
            u.sin_cos(&u.mul(&r, &self.degree))
        };
        match turns.rem_euclid(4) {
            0 => (s, c),
            1 => (c, s.neg()),
            2 => (s.neg(), c.neg()),
            _ => (c.neg(), s),
        }
    }

    fn a3f(&self, eps: &Real) -> Real {
        self.unit.horner(&self.a3x, eps)
    }

    /// `C₃[1..ORDER)`, at index `l`; index 0 unused.
    fn c3f(&self, eps: &Real) -> Vec<Real> {
        let u = &self.unit;
        let mut c = vec![Real::zero(); ORDER];
        let mut mult = self.one();
        let mut o = 0;
        for (l, slot) in c.iter_mut().enumerate().skip(1) {
            let m = ORDER - l - 1;
            mult = u.mul(&mult, eps);
            let p = self.c3x.get(o..=o + m).unwrap_or(&[]);
            *slot = u.mul(&mult, &u.horner(p, eps));
            o += m + 1;
        }
        c
    }

    /// `C₄[0..ORDER)`.
    fn c4f(&self, eps: &Real) -> Vec<Real> {
        let u = &self.unit;
        let mut c = Vec::with_capacity(ORDER);
        let mut mult = self.one();
        let mut o = 0;
        for l in 0..ORDER {
            let m = ORDER - l - 1;
            let p = self.c4x.get(o..=o + m).unwrap_or(&[]);
            c.push(u.mul(&mult, &u.horner(p, eps)));
            o += m + 1;
            mult = u.mul(&mult, eps);
        }
        c
    }

    /// `ε` from `k² = cos²α₀ e'²`: `k² / (2(1 + √(1 + k²)) + k²)`.
    fn epsilon(&self, calp0: &Real) -> Real {
        let u = &self.unit;
        let k2 = u.mul(&u.sq(calp0), &self.ep2);
        let root = u.sqrt(&self.one().add(&k2));
        u.div(&k2, &self.one().add(&root).times(2).add(&k2))
    }

    /// GeographicLib's `Lengths`: the distance over `b` and, if asked, the
    /// reduced length over `b`, from the auxiliary sphere's arc.
    #[allow(clippy::too_many_arguments)]
    fn lengths(
        &self,
        eps: &Real,
        sig12: &Real,
        (ssig1, csig1, dn1): (&Real, &Real, &Real),
        (ssig2, csig2, dn2): (&Real, &Real, &Real),
        distance: bool,
        with_m12: bool,
    ) -> (Real, Real) {
        let u = &self.unit;
        let one = self.one();
        let mut a1 = a1m1f(u, eps);
        let ca = c1f(u, eps);
        let mut a2 = Real::zero();
        let mut cb = vec![Real::zero(); ORDER + 1];
        let mut m0x = Real::zero();
        if with_m12 {
            a2 = a2m1f(u, eps);
            cb = c2f(u, eps);
            m0x = a1.sub(&a2);
            a2 = one.add(&a2);
        }
        a1 = one.add(&a1);
        let mut s12b = Real::zero();
        let mut j12 = Real::zero();
        if distance {
            let b1 = sin_cos_series(u, true, ssig2, csig2, &ca, ORDER)
                .sub(&sin_cos_series(u, true, ssig1, csig1, &ca, ORDER));
            s12b = u.mul(&a1, &sig12.add(&b1));
            if with_m12 {
                let b2 = sin_cos_series(u, true, ssig2, csig2, &cb, ORDER)
                    .sub(&sin_cos_series(u, true, ssig1, csig1, &cb, ORDER));
                j12 = u
                    .mul(&m0x, sig12)
                    .add(&u.mul(&a1, &b1).sub(&u.mul(&a2, &b2)));
            }
        } else if with_m12 {
            for l in 1..=ORDER {
                let (Some(c1), Some(c2)) = (ca.get(l), cb.get(l)) else {
                    continue;
                };
                let mixed = u.mul(&a1, c1).sub(&u.mul(&a2, c2));
                if let Some(slot) = cb.get_mut(l) {
                    *slot = mixed;
                }
            }
            j12 = u.mul(&m0x, sig12).add(
                &sin_cos_series(u, true, ssig2, csig2, &cb, ORDER)
                    .sub(&sin_cos_series(u, true, ssig1, csig1, &cb, ORDER)),
            );
        }
        let mut m12b = Real::zero();
        if with_m12 {
            m12b = u
                .mul(dn2, &u.mul(csig1, ssig2))
                .sub(&u.mul(dn1, &u.mul(ssig1, csig2)))
                .sub(&u.mul(&u.mul(csig1, csig2), &j12));
        }
        (s12b, m12b)
    }

    /// GeographicLib's `Astroid`: the positive root `k` of
    /// `k⁴ + 2k³ - (x² + y² - 1)k² - 2y²k - y² = 0`.
    fn astroid(&self, x: &Real, y: &Real) -> Real {
        let u = &self.unit;
        let one = self.one();
        let p = u.sq(x);
        let q = u.sq(y);
        let r = p.add(&q).sub(&one).div_whole(6);
        if q.is_zero() && r.signum() <= 0 {
            return Real::zero();
        }
        let s = u.mul(&p, &q).div_whole(4);
        let r2 = u.sq(&r);
        let r3 = u.mul(&r, &r2);
        let disc = u.mul(&s, &s.add(&r3.times(2)));
        let mut uu = r;
        if disc.signum() >= 0 {
            let mut t3 = s.add(&r3);
            let root = u.sqrt(&disc);
            t3 = if t3.is_negative() {
                t3.sub(&root)
            } else {
                t3.add(&root)
            };
            let t = u.cbrt(&t3);
            uu = uu.add(&t);
            if !t.is_zero() {
                uu = uu.add(&u.div(&r2, &t));
            }
        } else {
            let ang = u.atan2(&u.sqrt(&disc.neg()), &s.add(&r3).neg());
            let (_, c) = u.sin_cos(&ang.div_whole(3));
            uu = uu.add(&u.mul(&r, &c).times(2));
        }
        let v = u.sqrt(&u.sq(&uu).add(&q));
        let uv = if uu.is_negative() {
            u.div(&q, &v.sub(&uu))
        } else {
            uu.add(&v)
        };
        let w = u.div(&uv.sub(&q), &v.times(2));
        u.div(&uv, &u.sqrt(&uv.add(&u.sq(&w))).add(&w))
    }
}

/// One polynomial in `n` from a coefficient table: `m + 1` whole numbers
/// from `o`, then their divisor.
fn coefficient(unit: &Unit, table: &[i64], o: usize, m: usize, n: &Real) -> Real {
    let p = table.get(o..=o + m).unwrap_or(&[]);
    let divisor = table.get(o + m + 1).copied().unwrap_or(1);
    unit.polynomial(p, n, divisor)
}

fn a1m1f(u: &Unit, eps: &Real) -> Real {
    let t = coefficient(u, &A1M1, 0, ORDER / 2, &u.sq(eps));
    let one = u.int(1);
    u.div(&t.add(eps), &one.sub(eps))
}

fn a2m1f(u: &Unit, eps: &Real) -> Real {
    let t = coefficient(u, &A2M1, 0, ORDER / 2, &u.sq(eps));
    let one = u.int(1);
    u.div(&t.sub(eps), &one.add(eps))
}

/// `C₁[1..=ORDER]` or `C₂[1..=ORDER]`, at index `l`; index 0 unused.
fn fourier(u: &Unit, table: &[i64], eps: &Real) -> Vec<Real> {
    let eps2 = u.sq(eps);
    let mut d = *eps;
    let mut c = vec![Real::zero(); ORDER + 1];
    let mut o = 0;
    for (l, slot) in c.iter_mut().enumerate().skip(1) {
        let m = (ORDER - l) / 2;
        *slot = u.mul(&d, &coefficient(u, table, o, m, &eps2));
        o += m + 2;
        d = u.mul(&d, eps);
    }
    c
}

fn c1f(u: &Unit, eps: &Real) -> Vec<Real> {
    fourier(u, &C1, eps)
}

fn c2f(u: &Unit, eps: &Real) -> Vec<Real> {
    fourier(u, &C2, eps)
}

/// Clenshaw's sum of `c[l] sin(2l x)` for `l` from 1 to `n` (`sinp`), or
/// of `c[l] cos((2l + 1) x)` for `l` from 0 below `n`.
fn sin_cos_series(u: &Unit, sinp: bool, sinx: &Real, cosx: &Real, c: &[Real], n: usize) -> Real {
    let at = |index: usize| c.get(index).cloned().unwrap_or_else(Real::zero);
    let mut index = n + usize::from(sinp);
    let ar = u.mul(&cosx.sub(sinx), &cosx.add(sinx)).times(2);
    let mut y0 = if n % 2 == 1 {
        index -= 1;
        at(index)
    } else {
        Real::zero()
    };
    let mut y1 = Real::zero();
    for _ in 0..n / 2 {
        index -= 1;
        y1 = u.mul(&ar, &y0).sub(&y1).add(&at(index));
        index -= 1;
        y0 = u.mul(&ar, &y1).sub(&y0).add(&at(index));
    }
    if sinp {
        u.mul(&u.mul(sinx, cosx).times(2), &y0)
    } else {
        u.mul(cosx, &y0.sub(&y1))
    }
}

/// What the inverse problem gives: the distance in metres, the azimuth
/// at the first point as its sine and cosine, and the area between the
/// geodesic and the equator in square metres, counterclockwise.
pub(crate) struct Inverse {
    pub(crate) distance: Real,
    pub(crate) salp1: Real,
    pub(crate) calp1: Real,
    pub(crate) area: Real,
}

/// A short line's answer on the auxiliary sphere: `σ₁₂`, `sin α₂`,
/// `cos α₂` and the mean `√(1 + e'² sin²β)`.
type Short = (Real, Real, Real, Real);

/// What `lambda12` gives back besides `λ₁₂`.
struct Lambda {
    lam12: Real,
    salp2: Real,
    calp2: Real,
    sig12: Real,
    ssig1: Real,
    csig1: Real,
    ssig2: Real,
    csig2: Real,
    eps: Real,
    domg12: Real,
    dlam12: Real,
}

/// The reduced latitudes' sines, cosines and `√(1 + e'² sin²β)`.
struct Ends {
    sbet1: Real,
    cbet1: Real,
    dn1: Real,
    sbet2: Real,
    cbet2: Real,
    dn2: Real,
}

impl Ellipsoid {
    /// GeographicLib's `Lambda12`: the longitude difference a geodesic
    /// leaving the first point at the azimuth (`salp1`, `calp1`) has when
    /// it reaches the second point's latitude, minus the one wanted, and
    /// its derivative by the azimuth when `diffp`.
    fn lambda12(
        &self,
        ends: &Ends,
        salp1: &Real,
        calp1: &Real,
        (slam120, clam120): (&Real, &Real),
        diffp: bool,
    ) -> Lambda {
        let u = &self.unit;
        let Ends {
            sbet1,
            cbet1,
            dn1,
            sbet2,
            cbet2,
            dn2,
        } = ends;
        let calp1 = if sbet1.is_zero() && calp1.is_zero() {
            Real::tiny().neg()
        } else {
            *calp1
        };
        let salp0 = u.mul(salp1, cbet1);
        let calp0 = u.hypot(&calp1, &u.mul(salp1, sbet1));
        let somg1 = u.mul(&salp0, sbet1);
        let comg1 = u.mul(&calp1, cbet1);
        let (ssig1, csig1) = u.norm(sbet1, &comg1);
        let salp2 = if cbet2 != cbet1 {
            u.div(&salp0, cbet2)
        } else {
            *salp1
        };
        let calp2 = if cbet2 != cbet1 || sbet2.abs() != sbet1.neg() {
            let wide = if *cbet1 < sbet1.neg() {
                u.mul(&cbet2.sub(cbet1), &cbet1.add(cbet2))
            } else {
                u.mul(&sbet1.sub(sbet2), &sbet1.add(sbet2))
            };
            u.div(
                &u.sqrt(&u.sq(&u.mul(&calp1, cbet1)).add(&wide).max(Real::zero())),
                cbet2,
            )
        } else {
            calp1.abs()
        };
        let somg2 = u.mul(&salp0, sbet2);
        let comg2 = u.mul(&calp2, cbet2);
        let (ssig2, csig2) = u.norm(sbet2, &comg2);
        let sig12 = u.atan2(
            &u.mul(&csig1, &ssig2)
                .sub(&u.mul(&ssig1, &csig2))
                .max(Real::zero()),
            &u.mul(&csig1, &csig2).add(&u.mul(&ssig1, &ssig2)),
        );
        let somg12 = u
            .mul(&comg1, &somg2)
            .sub(&u.mul(&somg1, &comg2))
            .max(Real::zero());
        let comg12 = u.mul(&comg1, &comg2).add(&u.mul(&somg1, &somg2));
        let eta = u.atan2(
            &u.mul(&somg12, clam120).sub(&u.mul(&comg12, slam120)),
            &u.mul(&comg12, clam120).add(&u.mul(&somg12, slam120)),
        );
        let eps = self.epsilon(&calp0);
        let c3 = self.c3f(&eps);
        let b312 = sin_cos_series(u, true, &ssig2, &csig2, &c3, ORDER - 1).sub(&sin_cos_series(
            u,
            true,
            &ssig1,
            &csig1,
            &c3,
            ORDER - 1,
        ));
        let domg12 = u
            .mul(
                &u.mul(&u.mul(&self.f, &self.a3f(&eps)), &salp0),
                &sig12.add(&b312),
            )
            .neg();
        let lam12 = eta.add(&domg12);
        let mut dlam12 = Real::zero();
        if diffp {
            dlam12 = if calp2.is_zero() {
                u.div(&u.mul(&self.f1, dn1).times(-2), sbet1)
            } else {
                let (_, m12b) = self.lengths(
                    &eps,
                    &sig12,
                    (&ssig1, &csig1, dn1),
                    (&ssig2, &csig2, dn2),
                    false,
                    true,
                );
                u.div(&u.mul(&m12b, &self.f1), &u.mul(&calp2, cbet2))
            };
        }
        Lambda {
            lam12,
            salp2,
            calp2,
            sig12,
            ssig1,
            csig1,
            ssig2,
            csig2,
            eps,
            domg12,
            dlam12,
        }
    }

    /// GeographicLib's `InverseStart`: a first azimuth for Newton's method
    /// and, for a short line, the whole answer on the auxiliary sphere.
    fn inverse_start(
        &self,
        ends: &Ends,
        (lam12, slam12, clam12): (&Real, &Real, &Real),
    ) -> ((Real, Real), Option<Short>) {
        let u = &self.unit;
        let one = self.one();
        let Ends {
            sbet1,
            cbet1,
            sbet2,
            cbet2,
            ..
        } = ends;
        let sbet12 = u.mul(sbet2, cbet1).sub(&u.mul(cbet2, sbet1));
        let cbet12 = u.mul(cbet2, cbet1).add(&u.mul(sbet2, sbet1));
        let sbet12a = u.mul(sbet2, cbet1).add(&u.mul(cbet2, sbet1));
        let half = u.ratio(1, 2);
        let shortline = !cbet12.is_negative() && sbet12 < half && u.mul(cbet2, lam12) < half;
        let mut dnm = one;
        let (mut somg12, mut comg12) = (*slam12, *clam12);
        if shortline {
            let sum = sbet1.add(sbet2);
            let sbetm2 = u.sq(&sum);
            let sbetm2 = u.div(&sbetm2, &sbetm2.add(&u.sq(&cbet1.add(cbet2))));
            dnm = u.sqrt(&one.add(&u.mul(&self.ep2, &sbetm2)));
            let omg12 = u.div(lam12, &u.mul(&self.f1, &dnm));
            (somg12, comg12) = u.sin_cos(&omg12);
        }
        let mut salp1 = u.mul(cbet2, &somg12);
        let mut calp1 = if !comg12.is_negative() {
            sbet12.add(&u.div(
                &u.mul(&u.mul(cbet2, sbet1), &u.sq(&somg12)),
                &one.add(&comg12),
            ))
        } else {
            sbet12a.sub(&u.div(
                &u.mul(&u.mul(cbet2, sbet1), &u.sq(&somg12)),
                &one.sub(&comg12),
            ))
        };
        let ssig12 = u.hypot(&salp1, &calp1);
        let csig12 = u
            .mul(sbet1, sbet2)
            .add(&u.mul(&u.mul(cbet1, cbet2), &comg12));
        let mut short = None;
        if shortline && ssig12 < self.etol2 {
            let salp2 = u.mul(cbet1, &somg12);
            let calp2 = sbet12.sub(&u.mul(
                &u.mul(cbet1, sbet2),
                &if !comg12.is_negative() {
                    u.div(&u.sq(&somg12), &one.add(&comg12))
                } else {
                    one.sub(&comg12)
                },
            ));
            let (salp2, calp2) = u.norm(&salp2, &calp2);
            short = Some((u.atan2(&ssig12, &csig12), salp2, calp2, dnm));
        } else if !csig12.is_negative()
            || ssig12 >= u.mul(&u.mul(&self.n.times(6), u.pi()), &u.sq(cbet1))
        {
            // The sphere's estimate stands.
        } else {
            // Near the antipode: scaled so the antipodal point is the
            // origin and the singular point (x, y) = (-1, 0).
            let lam12x = u.atan2(&slam12.neg(), &clam12.neg());
            let k2 = u.mul(&u.sq(sbet1), &self.ep2);
            let eps = u.div(&k2, &one.add(&u.sqrt(&one.add(&k2))).times(2).add(&k2));
            let lamscale = u.mul(&u.mul(&u.mul(&self.f, cbet1), &self.a3f(&eps)), u.pi());
            let betscale = u.mul(&lamscale, cbet1);
            let x = u.div(&lam12x, &lamscale);
            let y = u.div(&sbet12a, &betscale);
            if y > self.tol1.neg() && x > one.add(&self.xthresh).neg() {
                salp1 = if x.neg() < one { x.neg() } else { one };
                calp1 = u.sqrt(&one.sub(&u.sq(&salp1))).neg();
            } else {
                let k = self.astroid(&x, &y);
                let omg12a = u.mul(&lamscale, &u.div(&u.mul(&x.neg(), &k), &one.add(&k)));
                let (s, c) = u.sin_cos(&omg12a);
                somg12 = s;
                comg12 = c.neg();
                salp1 = u.mul(cbet2, &somg12);
                calp1 = sbet12a.sub(&u.div(
                    &u.mul(&u.mul(cbet2, sbet1), &u.sq(&somg12)),
                    &one.sub(&comg12),
                ));
            }
        }
        let start = if salp1.signum() > 0 {
            u.norm(&salp1, &calp1)
        } else {
            (one, Real::zero())
        };
        (start, short)
    }

    /// The inverse problem between (`lat1`, `lon1`) and (`lat2`, `lon2`),
    /// in degrees, GeographicLib's `GenInverse`; the area only when
    /// `area` asks.
    fn inverse(&self, lat1: &Real, lon1: &Real, lat2: &Real, lon2: &Real, area: bool) -> Inverse {
        let u = &self.unit;
        let one = self.one();
        let hd = u.int(180);
        // The longitude difference, exactly, from -180 to 180, a half turn
        // signed as `lon2 - lon1` is.
        let raw = lon2.sub(lon1);
        let mut lon12 = raw;
        if lon12 > hd {
            lon12 = lon12.sub(&hd.times(2));
        } else if lon12 < hd.neg() {
            lon12 = lon12.add(&hd.times(2));
        }
        if lon12.abs() == hd {
            lon12 = if raw.is_negative() { hd.neg() } else { hd };
        }
        let mut lonsign: i64 = if lon12.is_negative() { -1 } else { 1 };
        lon12 = lon12.times(lonsign);
        let lam12 = u.mul(&lon12, &self.degree);
        let (slam12, clam12) = self.sin_cos_degrees(&lon12);
        let lon12s = hd.sub(&lon12);
        let (mut lat1, mut lat2) = (*lat1, *lat2);
        let swapp: i64 = if lat1.abs() < lat2.abs() { -1 } else { 1 };
        if swapp < 0 {
            lonsign = -lonsign;
            std::mem::swap(&mut lat1, &mut lat2);
        }
        let latsign: i64 = if lat1.is_negative() { 1 } else { -1 };
        lat1 = lat1.times(latsign);
        lat2 = lat2.times(latsign);
        let on_sphere = |lat: &Real| {
            let (s, c) = self.sin_cos_degrees(lat);
            let (s, c) = u.norm(&u.mul(&s, &self.f1), &c);
            (s, c.max(Real::tiny()))
        };
        let (sbet1, cbet1) = on_sphere(&lat1);
        let (mut sbet2, mut cbet2) = on_sphere(&lat2);
        if cbet1 < sbet1.neg() {
            if cbet2 == cbet1 {
                sbet2 = if sbet2.is_negative() {
                    sbet1.abs().neg()
                } else {
                    sbet1.abs()
                };
            }
        } else if sbet2.abs() == sbet1.neg() {
            cbet2 = cbet1;
        }
        let dn = |sbet: &Real| u.sqrt(&one.add(&u.mul(&self.ep2, &u.sq(sbet))));
        let ends = Ends {
            dn1: dn(&sbet1),
            dn2: dn(&sbet2),
            sbet1,
            cbet1,
            sbet2,
            cbet2,
        };
        let Ends {
            sbet1,
            cbet1,
            sbet2,
            cbet2,
            dn1,
            dn2,
        } = &ends;

        let mut s12x = Real::zero();
        let (mut salp1, mut calp1, mut salp2, mut calp2);
        let mut omega: Option<(Real, Real)> = None;
        let mut omg12 = Real::zero();
        let mut meridian = lat1 == u.int(-90) || slam12.is_zero();
        if meridian {
            calp1 = clam12;
            salp1 = slam12;
            calp2 = one;
            salp2 = Real::zero();
            let ssig1 = *sbet1;
            let csig1 = u.mul(&calp1, cbet1);
            let ssig2 = *sbet2;
            let csig2 = u.mul(&calp2, cbet2);
            let sig12 = u.atan2(
                &u.mul(&csig1, &ssig2)
                    .sub(&u.mul(&ssig1, &csig2))
                    .max(Real::zero()),
                &u.mul(&csig1, &csig2).add(&u.mul(&ssig1, &ssig2)),
            );
            let (s, m) = self.lengths(
                &self.n,
                &sig12,
                (&ssig1, &csig1, dn1),
                (&ssig2, &csig2, dn2),
                true,
                true,
            );
            if sig12 < self.tol2 || !m.is_negative() {
                if sig12 < Real::tiny().times(3)
                    || (sig12 < self.tol0 && (s.is_negative() || m.is_negative()))
                {
                    s12x = Real::zero();
                } else {
                    s12x = u.mul(&s, &self.b);
                }
            } else {
                meridian = false;
            }
        } else {
            (salp1, calp1, salp2, calp2) = (Real::zero(), one, Real::zero(), one);
        }
        if !meridian && sbet1.is_zero() && lon12s >= u.mul(&self.f, &hd) {
            // Along the equator.
            calp1 = Real::zero();
            calp2 = Real::zero();
            salp1 = one;
            salp2 = one;
            s12x = u.mul(&self.a, &lam12);
            omg12 = u.div(&lam12, &self.f1);
        } else if !meridian {
            let ((s1, c1), short) = self.inverse_start(&ends, (&lam12, &slam12, &clam12));
            salp1 = s1;
            calp1 = c1;
            if let Some((sig12, s2, c2, dnm)) = short {
                salp2 = s2;
                calp2 = c2;
                s12x = u.mul(&u.mul(&sig12, &self.b), &dnm);
                omg12 = u.div(&lam12, &u.mul(&self.f1, &dnm));
            } else {
                let mut numit: u32 = 0;
                let (mut salp1a, mut calp1a) = (Real::tiny(), one);
                let (mut salp1b, mut calp1b) = (Real::tiny(), one.neg());
                let (mut tripn, mut tripb) = (false, false);
                let mut last;
                loop {
                    last = self.lambda12(&ends, &salp1, &calp1, (&slam12, &clam12), numit < NEWTON);
                    // λ₁₂ less the longitude difference wanted.
                    let v = last.lam12;
                    let bound = if tripn { self.tol0.times(8) } else { self.tol0 };
                    if tripb || v.abs() < bound || numit == LAST {
                        break;
                    }
                    let slope = |s: &Real, c: &Real| u.div(c, s);
                    if v.signum() > 0
                        && (numit > NEWTON || slope(&salp1, &calp1) > slope(&salp1b, &calp1b))
                    {
                        salp1b = salp1;
                        calp1b = calp1;
                    } else if v.is_negative()
                        && (numit > NEWTON || slope(&salp1, &calp1) < slope(&salp1a, &calp1a))
                    {
                        salp1a = salp1;
                        calp1a = calp1;
                    }
                    if numit < NEWTON && last.dlam12.signum() > 0 {
                        let dalp1 = u.div(&v, &last.dlam12).neg();
                        if dalp1.abs() < *u.pi() {
                            let (sdalp1, cdalp1) = u.sin_cos(&dalp1);
                            let nsalp1 = u.mul(&salp1, &cdalp1).add(&u.mul(&calp1, &sdalp1));
                            if nsalp1.signum() > 0 {
                                calp1 = u.mul(&calp1, &cdalp1).sub(&u.mul(&salp1, &sdalp1));
                                (salp1, calp1) = u.norm(&nsalp1, &calp1);
                                tripn = v.abs() <= self.tol0.times(16);
                                numit += 1;
                                continue;
                            }
                        }
                    }
                    // Newton's step went the wrong way or out of (0, π):
                    // the middle of the bracket instead.
                    salp1 = salp1a.add(&salp1b).div_whole(2);
                    calp1 = calp1a.add(&calp1b).div_whole(2);
                    (salp1, calp1) = u.norm(&salp1, &calp1);
                    tripn = false;
                    tripb = salp1a.sub(&salp1).abs().add(&calp1a.sub(&calp1)) < self.tolb
                        || salp1.sub(&salp1b).abs().add(&calp1.sub(&calp1b)) < self.tolb;
                    numit += 1;
                }
                let (s, _) = self.lengths(
                    &last.eps,
                    &last.sig12,
                    (&last.ssig1, &last.csig1, dn1),
                    (&last.ssig2, &last.csig2, dn2),
                    true,
                    false,
                );
                s12x = u.mul(&s, &self.b);
                salp2 = last.salp2;
                calp2 = last.calp2;
                if area {
                    let (sdomg12, cdomg12) = u.sin_cos(&last.domg12);
                    omega = Some((
                        u.mul(&slam12, &cdomg12).sub(&u.mul(&clam12, &sdomg12)),
                        u.mul(&clam12, &cdomg12).add(&u.mul(&slam12, &sdomg12)),
                    ));
                }
            }
        }

        let mut s12 = Real::zero();
        if area {
            let salp0 = u.mul(&salp1, cbet1);
            let calp0 = u.hypot(&calp1, &u.mul(&salp1, sbet1));
            if !calp0.is_zero() && !salp0.is_zero() {
                let (ssig1, csig1) = u.norm(sbet1, &u.mul(&calp1, cbet1));
                let (ssig2, csig2) = u.norm(sbet2, &u.mul(&calp2, cbet2));
                let eps = self.epsilon(&calp0);
                let a4 = u.mul(&u.mul(&u.mul(&u.sq(&self.a), &calp0), &salp0), &self.e2);
                let c4 = self.c4f(&eps);
                let b41 = sin_cos_series(u, false, &ssig1, &csig1, &c4, ORDER);
                let b42 = sin_cos_series(u, false, &ssig2, &csig2, &c4, ORDER);
                s12 = u.mul(&a4, &b42.sub(&b41));
            }
            let (somg12, comg12) = match omega {
                Some(pair) => pair,
                None if !meridian => u.sin_cos(&omg12),
                None => (Real::zero(), Real::zero()),
            };
            let alp12 = if !meridian
                && comg12 > u.ratio(-7071, 10_000)
                && sbet2.sub(sbet1) < u.ratio(175, 100)
            {
                let domg12 = one.add(&comg12);
                let dbet1 = one.add(cbet1);
                let dbet2 = one.add(cbet2);
                u.atan2(
                    &u.mul(&somg12, &u.mul(sbet1, &dbet2).add(&u.mul(sbet2, &dbet1))),
                    &u.mul(&domg12, &u.mul(sbet1, sbet2).add(&u.mul(&dbet1, &dbet2))),
                )
                .times(2)
            } else {
                let mut salp12 = u.mul(&salp2, &calp1).sub(&u.mul(&calp2, &salp1));
                let mut calp12 = u.mul(&calp2, &calp1).add(&u.mul(&salp2, &salp1));
                if salp12.is_zero() && calp12.is_negative() {
                    salp12 = calp1.tiny_as();
                    calp12 = one.neg();
                }
                u.atan2(&salp12, &calp12)
            };
            s12 = s12.add(&u.mul(&self.c2, &alp12));
            s12 = s12.times(swapp * lonsign * latsign);
        }
        if swapp < 0 {
            std::mem::swap(&mut salp1, &mut salp2);
            std::mem::swap(&mut calp1, &mut calp2);
        }
        salp1 = salp1.times(swapp * lonsign);
        calp1 = calp1.times(swapp * latsign);
        Inverse {
            distance: s12x,
            salp1,
            calp1,
            area: s12,
        }
    }
}

/// A point in degrees, as working values.
fn degrees(e: &Ellipsoid, (latitude, longitude): (Decimal, Decimal)) -> (Real, Real) {
    (e.unit.decimal(latitude), e.unit.decimal(longitude))
}

/// The geodesic distance between two points in metres, at 6 places
/// rounded half to even; `None` past 38 digits, which no distance on the
/// Earth reaches.
pub(crate) fn distance(from: (Decimal, Decimal), to: (Decimal, Decimal)) -> Option<i128> {
    let e = wgs84();
    let (lat1, lon1) = degrees(e, from);
    let (lat2, lon2) = degrees(e, to);
    e.inverse(&lat1, &lon1, &lat2, &lon2, false)
        .distance
        .rounded(6, jadpo_std::Rounding::HalfEven)
}

/// The geodesic's direction as it leaves `from`, in degrees clockwise
/// from true north, at least 0 and below 360, to 9 places rounded half to
/// even; the caller has ruled out two equal points.
pub(crate) fn bearing(from: (Decimal, Decimal), to: (Decimal, Decimal)) -> Option<i128> {
    let e = wgs84();
    let u = &e.unit;
    let (lat1, lon1) = degrees(e, from);
    let (lat2, lon2) = degrees(e, to);
    let solved = e.inverse(&lat1, &lon1, &lat2, &lon2, false);
    let mut degrees = u.div(&u.atan2(&solved.salp1, &solved.calp1), &e.degree);
    if degrees.is_negative() {
        degrees = degrees.add(&u.int(360));
    }
    let rounded = degrees.rounded(9, jadpo_std::Rounding::HalfEven)?;
    Some(if rounded >= 360 * 10i128.pow(9) {
        rounded - 360 * 10i128.pow(9)
    } else {
        rounded
    })
}

/// Whether the edge from longitude `lon1` to `lon2` crosses the prime
/// meridian eastward (1) or westward (-1), GeographicLib's `transit`, a
/// longitude of 0 counted as east of it.
fn transit(e: &Ellipsoid, lon1: &Real, lon2: &Real) -> i64 {
    let hd = e.unit.int(180);
    let raw = lon2.sub(lon1);
    let mut lon12 = raw;
    if lon12 > hd {
        lon12 = lon12.sub(&hd.times(2));
    } else if lon12 < hd.neg() {
        lon12 = lon12.add(&hd.times(2));
    }
    if lon12.abs() == hd {
        lon12 = if raw.is_negative() { hd.neg() } else { hd };
    }
    if lon12.signum() > 0
        && ((lon1.is_negative() && !lon2.is_negative()) || (lon1.signum() > 0 && lon2.is_zero()))
    {
        1
    } else if lon12.is_negative() && !lon1.is_negative() && lon2.is_negative() {
        -1
    } else {
        0
    }
}

/// A ring's area in square metres, the smaller of the two sides it
/// bounds, as PostGIS reads a ring either way round: Karney's polygon
/// method, each edge's area under its geodesic summed with the prime
/// meridian's crossings counted, reduced modulo the ellipsoid's area.
/// Unrounded, so a polygon's holes are taken away before it is rounded.
pub(crate) fn ring_area(ring: &[(Decimal, Decimal)]) -> Real {
    let e = wgs84();
    let u = &e.unit;
    let points: Vec<(Real, Real)> = ring.iter().map(|point| degrees(e, *point)).collect();
    let Some(first) = points.first() else {
        return Real::zero();
    };
    let mut sum = Real::zero();
    let mut crossings: i64 = 0;
    let mut closing = points.clone();
    if points.last() != Some(first) {
        closing.push(*first);
    }
    for pair in closing.windows(2) {
        let [(lat1, lon1), (lat2, lon2)] = pair else {
            continue;
        };
        sum = sum.add(&e.inverse(lat1, lon1, lat2, lon2, true).area);
        crossings += transit(e, lon1, lon2);
    }
    // 4πc², the whole ellipsoid; the sum reduced to within half of it of
    // 0, as `remainder` does, then a half added or taken for an odd number
    // of crossings, then to (-half, half].
    let whole = u.mul(&u.pi().times(4), &e.c2);
    let half = whole.div_whole(2);
    let mut area = sum;
    while area > half {
        area = area.sub(&whole);
    }
    while area < half.neg() {
        area = area.add(&whole);
    }
    if crossings % 2 != 0 {
        area = if area.is_negative() {
            area.add(&half)
        } else {
            area.sub(&half)
        };
    }
    if area > half {
        area = area.sub(&whole);
    } else if area <= half.neg() {
        area = area.add(&whole);
    }
    area.abs()
}

/// An area in square metres, held unrounded while a polygon's rings and
/// a multi-polygon's polygons are summed.
pub(crate) struct Area(Real);

impl Area {
    pub(crate) fn zero() -> Area {
        Area(Real::zero())
    }

    /// A ring's area, the smaller side ([`ring_area`]).
    pub(crate) fn of_ring(ring: &[(Decimal, Decimal)]) -> Area {
        Area(ring_area(ring))
    }

    pub(crate) fn plus(&self, other: &Area) -> Area {
        Area(self.0.add(&other.0))
    }

    pub(crate) fn less(&self, other: &Area) -> Area {
        Area(self.0.sub(&other.0))
    }

    /// In square metres at 6 places, rounded half to even.
    pub(crate) fn square_metres(&self) -> Option<i128> {
        square_metres(&self.0)
    }
}

/// An area in square metres at 6 places, rounded half to even.
pub(crate) fn square_metres(area: &Real) -> Option<i128> {
    area.rounded(6, jadpo_std::Rounding::HalfEven)
}

