//! Which wording each translation was made from, and who has accepted it
//! (area 10, "Translations as messages"; area 18's `translations` record).
//!
//! Each `translations/` folder has a committed `sources.jadpo_record`, one
//! line for each locale and member outside the default locale:
//!
//! ```text
//! translation de_de.order_shipped from 3f9a1c0e2b7d wording 77b2e1d4c8a9 accepted
//! ```
//!
//! `from` is the hash of the default locale's wording when the translation
//! was recorded, `wording` the hash of the translation itself, and
//! `accepted` is there once a person accepted that wording. Whether a
//! translation is stale is computed, never stored: its `from` differs from
//! the hash of the default wording today. Whether it is unaccepted is
//! computed too: the line is missing, says another wording, or lacks
//! `accepted`. A hash covers the member's whole text, every value and
//! plural form, in name order, so reordering a block changes nothing.
//!
//! The file is the translations record's first writer: chunk 7.0 moves the
//! generic header check, `jadpo records` and the hand-edit error to every
//! record, and keeps this format.

use jadpo_db::{Db, Project};
use jadpo_diag::{Diagnostic, Span, nearest, rule};
use jadpo_syntax::ast::AstNode;

use super::declared::{Kind, SHARED, language_files, subjects};
use super::language::{Body, language_file};
use crate::config::singletons;
use crate::lookups::Name;
use crate::tree::{self, node_span};
use crate::types::Const;

/// The record's file name, in each `translations/` folder.
pub const FILE: &str = "sources.jadpo_record";

/// The first line of the record.
pub const HEADER: &str = "// Generated by Jadpo from this folder's translations; update it with `jadpo translations update`, never by hand.";

/// The second line.
const KIND: &str = "record translations 1";

/// The record of a scope's translations folder.
pub fn record_path(scope: &str) -> String {
    if scope == SHARED {
        format!("shared/translations/{FILE}")
    } else {
        format!("domains/{scope}/translations/{FILE}")
    }
}

/// One line of the record.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Entry {
    /// The locale, in the spelling `Locale.<tag>` uses.
    pub locale: String,
    pub member: String,
    /// The hash of the default wording it was made from.
    pub from: String,
    /// The hash of its own wording when that was recorded.
    pub wording: String,
    pub accepted: bool,
}

/// The hash a record holds: 12 lower-case hex digits of the text. It is
/// not a security check, so 48 bits is plenty.
pub fn hash(text: &str) -> String {
    blake3::hash(text.as_bytes()).to_hex()[..12].to_string()
}

/// A member's whole wording as one string, values and plural forms in name
/// order.
pub fn canonical(body: &Body) -> String {
    match body {
        Body::Text(written) => written.text.clone(),
        Body::Variants(variants) => {
            let mut parts: Vec<String> = variants
                .iter()
                .map(|variant| {
                    format!(
                        "{}={}",
                        variant.name,
                        variant.written.as_ref().map_or("", |written| &written.text)
                    )
                })
                .collect();
            parts.sort();
            parts.join("\u{1f}")
        }
        Body::Invalid => String::new(),
    }
}

/// The record's lines, sorted, under its header.
pub fn render(entries: &[Entry]) -> String {
    let mut sorted: Vec<&Entry> = entries.iter().collect();
    sorted.sort_by(|a, b| (&a.locale, &a.member).cmp(&(&b.locale, &b.member)));
    let mut out = format!("{HEADER}\n{KIND}\n");
    if !sorted.is_empty() {
        out.push('\n');
    }
    for entry in sorted {
        out.push_str(&format!(
            "translation {}.{} from {} wording {}{}\n",
            entry.locale,
            entry.member,
            entry.from,
            entry.wording,
            if entry.accepted { " accepted" } else { "" }
        ));
    }
    out
}

/// The lines of a record, or what is wrong with it and on which line.
pub fn parse(text: &str) -> Result<Vec<Entry>, (usize, String)> {
    let mut lines = text.lines().enumerate();
    match lines.next() {
        Some((_, line)) if line == HEADER => {}
        Some((at, _)) => {
            return Err((
                at,
                "the first line is not the header Jadpo writes".to_string(),
            ));
        }
        None => return Err((0, "the file is empty".to_string())),
    }
    match lines.next() {
        Some((_, line)) if line == KIND => {}
        Some((at, line)) if line.starts_with("record translations ") => {
            return Err((at, "this record was written by a newer Jadpo".to_string()));
        }
        Some((at, _)) => {
            return Err((
                at,
                "the second line is not `record translations 1`".to_string(),
            ));
        }
        None => return Err((1, "the file ends after the header".to_string())),
    }
    let mut entries = Vec::new();
    for (at, line) in lines {
        if line.is_empty() {
            continue;
        }
        let words: Vec<&str> = line.split(' ').collect();
        let accepted = match words.as_slice() {
            ["translation", _, "from", _, "wording", _] => false,
            ["translation", _, "from", _, "wording", _, "accepted"] => true,
            _ => return Err((at, "this line is not a translation entry".to_string())),
        };
        let Some((locale, member)) = words[1].split_once('.') else {
            return Err((at, "the entry names no member".to_string()));
        };
        let is_hash = |text: &str| {
            text.len() == 12
                && text
                    .bytes()
                    .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
        };
        if locale.is_empty() || member.is_empty() || !is_hash(words[3]) || !is_hash(words[5]) {
            return Err((at, "this line is not a translation entry".to_string()));
        }
        entries.push(Entry {
            locale: locale.to_string(),
            member: member.to_string(),
            from: words[3].to_string(),
            wording: words[5].to_string(),
            accepted,
        });
    }
    Ok(entries)
}

/// How one translation stands against its record.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Standing {
    pub scope: String,
    /// The locale's place among `Locale`'s variants.
    pub locale: u32,
    pub tag: String,
    pub member: String,
    /// The locale's language file, and the member's key in it.
    pub path: String,
    pub key_span: Span,
    /// The default locale's member.
    pub default_tag: String,
    pub default_span: Span,
    pub default_hash: String,
    pub wording_hash: String,
    /// The record's line for it, if any.
    pub recorded: Option<Entry>,
    /// Made from default wording that has changed.
    pub stale: bool,
    /// Whether the locale's translations are in progress.
    pub in_progress: bool,
}

impl Standing {
    /// Whether a person accepted exactly this wording.
    pub fn accepted(&self) -> bool {
        self.recorded
            .as_ref()
            .is_some_and(|entry| entry.accepted && entry.wording == self.wording_hash)
    }

    /// Whether the wording differs from the one the record holds, or the
    /// record has none: new or changed since `jadpo translations update`.
    pub fn changed(&self) -> bool {
        self.recorded
            .as_ref()
            .is_none_or(|entry| entry.wording != self.wording_hash)
    }
}

/// A scope's translations against its record.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Standings {
    pub list: Vec<Standing>,
    /// The record's lines, when it reads.
    pub record: Vec<Entry>,
    /// Whether a record exists for the folder.
    pub has_record: bool,
    pub problems: Vec<Diagnostic>,
}

/// Every translation outside the default locale in a scope, against the
/// scope's `sources.jadpo_record`. Meant for a project whose locales read
/// cleanly.
#[salsa::tracked(returns(ref))]
pub fn standings<'db>(db: &'db dyn Db, project: Project, scope: Name<'db>) -> Standings {
    let scope = scope.text(db).clone();
    let mut out = Standings::default();
    let declared = crate::locales::locales(db, project);
    let Some(plan) = &declared.plan else {
        return out;
    };
    let path = record_path(&scope);
    if let Some(record) = project
        .records(db)
        .iter()
        .find(|record| record.path == path)
    {
        out.has_record = true;
        match &record.text {
            Ok(text) => match parse(text) {
                Ok(entries) => out.record = entries,
                Err((at, why)) => out.problems.push(invalid(&path, text, at, &why)),
            },
            Err(error) => out.problems.push(
                Diagnostic::new(
                    &rule::TRANSLATION_SOURCES_INVALID,
                    format!("`{path}` couldn't be read"),
                )
                .at(Span::new(&path, 0, 0), "unreadable")
                .reason(format!("Reading it failed: {error}."))
                .next("Run `jadpo translations update`, which writes it again"),
            ),
        }
    }
    let subjects = subjects(db, project, Name::new(db, scope.clone()));
    let files: Vec<_> = language_files(db, project, &scope)
        .into_iter()
        .filter_map(|file| language_file(db, project, file).as_ref())
        .collect();
    let Some(default_file) = files.iter().find(|file| file.locale == Some(plan.default)) else {
        return out;
    };
    let default_tag = default_file.tag.clone();
    for file in &files {
        let Some(locale) = file.locale else { continue };
        if locale == plan.default || !plan.supports(locale) {
            continue;
        }
        for member in &file.members {
            let Some(subject) = subjects.get(&member.name) else {
                continue;
            };
            if subject.broken || member.body == Body::Invalid {
                continue;
            }
            let Some(default) = default_file.member(&member.name) else {
                continue;
            };
            if default.body == Body::Invalid {
                continue;
            }
            let default_hash = hash(&canonical(&default.body));
            let recorded = out
                .record
                .iter()
                .find(|entry| entry.locale == file.tag && entry.member == member.name)
                .cloned();
            let stale = recorded
                .as_ref()
                .is_some_and(|entry| entry.from != default_hash);
            out.list.push(Standing {
                scope: scope.clone(),
                locale,
                tag: file.tag.clone(),
                member: member.name.clone(),
                path: file.path.clone(),
                key_span: member.key_span.clone(),
                default_tag: default_tag.clone(),
                default_span: default.key_span.clone(),
                default_hash,
                wording_hash: hash(&canonical(&member.body)),
                recorded,
                stale,
                in_progress: plan.in_progress.contains(&locale),
            });
        }
    }
    out.list
        .sort_by(|a, b| (&a.tag, &a.member).cmp(&(&b.tag, &b.member)));
    // A stale translation is an error, unless its locale is in progress,
    // where `jadpo translations missing` lists it instead.
    for standing in &out.list {
        if standing.stale && !standing.in_progress {
            out.problems.push(stale(
                standing,
                subjects.get(&standing.member).map(|s| s.kind),
            ));
        }
    }
    out
}

fn invalid(path: &str, text: &str, line: usize, why: &str) -> Diagnostic {
    let start: usize = text.lines().take(line).map(|l| l.len() + 1).sum();
    let end = start + text.lines().nth(line).map_or(0, str::len);
    Diagnostic::new(
        &rule::TRANSLATION_SOURCES_INVALID,
        format!("`{path}` can't be read: {why}"),
    )
    .at(
        Span::new(path, start as u32, end.max(start + 1) as u32),
        why.to_string(),
    )
    .reason("This file records which wording each translation was made from and who accepted it. Jadpo writes it, and a stale or unaccepted translation is judged from it, so a file it can't read hides both.")
    .next("Run `jadpo translations update`, which writes it again")
}

fn stale(standing: &Standing, kind: Option<Kind>) -> Diagnostic {
    let what = kind.map_or("translation", Kind::word);
    Diagnostic::new(
        &rule::TRANSLATION_STALE,
        format!(
            "`{}` in `{}` was translated from `{}` wording that has since changed",
            standing.member, standing.tag, standing.default_tag
        ),
    )
    .at(
        standing.key_span.clone(),
        format!("made from the old `{}` wording", standing.default_tag),
    )
    .also(standing.default_span.clone(), "the wording now")
    .reason(format!(
        "`jadpo translations update` recorded the `{}` wording this {what}'s translation was made from, and the `{}` wording has changed since, so the translation may no longer say the same thing.",
        standing.default_tag, standing.default_tag
    ))
    .next(format!(
        "Reword `{}` in `{}` to match the new `{}` wording, then run `jadpo translations update`",
        standing.member, standing.path, standing.default_tag
    ))
}

/// What `translations: { review: ... }` in `app.jadpo` says.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Review {
    /// `TranslationReview.required`.
    pub required: bool,
    pub problems: Vec<Diagnostic>,
}

const OPTIONS: [&str; 1] = ["review"];

/// The application's translation review setting (area 10, "Translations as
/// messages"): `translations: { review: TranslationReview.required }` in
/// `application { }`, `TranslationReview.none` when it says nothing.
#[salsa::tracked(returns(ref))]
pub fn review(db: &dyn Db, project: Project) -> Review {
    let mut out = Review::default();
    for found in singletons(db, project, "application") {
        for (key, member) in tree::members(found.list.clone()) {
            if tree::name_text(&key).as_deref() != Some("translations") {
                continue;
            }
            let mut seen = false;
            for (name, option) in tree::members(member.block()) {
                let Some(text) = tree::name_text(&name) else {
                    continue;
                };
                let name_span = node_span(&found.path, name.syntax());
                if text != "review" {
                    let near = nearest(&text, OPTIONS);
                    let problem = Diagnostic::new(
                        &rule::TRANSLATION_OPTION_UNKNOWN,
                        format!("`{text}` isn't an option of `translations`"),
                    )
                    .at(name_span.clone(), "unknown option")
                    .reason(format!(
                        "`translations:` in `application` takes `review:` and nothing else.{}",
                        near.map_or_else(String::new, |near| format!(" Did you mean `{near}`?"))
                    ));
                    out.problems.push(match near {
                        Some(near) => problem
                            .next(format!("Use `{near}` instead of `{text}`"))
                            .edit(name_span, near),
                        None => problem.next(format!("Remove `{text}:`")),
                    });
                    continue;
                }
                if seen {
                    continue;
                }
                seen = true;
                let Some(value) = option.value() else {
                    out.problems.push(invalid_review(name_span, None));
                    continue;
                };
                let value_span = node_span(&found.path, value.syntax());
                match Const::from_expr(&value) {
                    Const::Path(path)
                        if path.len() == 2 && path[0] == jadpo_std::TranslationReview::NAME =>
                    {
                        match jadpo_std::TranslationReview::from_name(&path[1]) {
                            Some(jadpo_std::TranslationReview::Required) => out.required = true,
                            Some(jadpo_std::TranslationReview::None) => {}
                            None => out
                                .problems
                                .push(invalid_review(value_span, Some(&path[1]))),
                        }
                    }
                    _ => out.problems.push(invalid_review(value_span, None)),
                }
            }
        }
    }
    out
}

fn invalid_review(at: Span, variant: Option<&str>) -> Diagnostic {
    let names = jadpo_std::TranslationReview::NAMES;
    let near = variant.and_then(|variant| nearest(variant, names.iter().copied()));
    let problem = Diagnostic::new(
        &rule::TRANSLATION_REVIEW_INVALID,
        "`review:` isn't a `TranslationReview`",
    )
    .at(at.clone(), "not `TranslationReview.none` or `.required`")
    .reason(format!(
        "`review:` says whether wording outside the default locale waits for a person to accept it: `TranslationReview.none`, the default, or `TranslationReview.required`.{}",
        near.map_or_else(String::new, |near| format!(
            " Did you mean `TranslationReview.{near}`?"
        ))
    ));
    match near {
        Some(near) => problem
            .next(format!("Use `TranslationReview.{near}`"))
            .edit(at, format!("TranslationReview.{near}")),
        None => problem.next("Write `review: TranslationReview.required`, or leave `review:` out"),
    }
}

/// What a translation's line did when the record was brought up to date.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Change {
    /// A translation the record had no line for.
    Recorded,
    /// A translation whose wording changed since its line was written: its
    /// line now says it was made from today's default wording, and drops
    /// its acceptance.
    Reworded,
    /// A line for a translation that is gone.
    Removed,
    /// A person accepted its wording.
    Accepted,
    /// Made from default wording that has changed and not reworded since:
    /// its line is left as it was, and `accept` leaves it alone.
    StillStale,
}

/// The record after `jadpo translations update`, or after `jadpo
/// translations accept` for the locale `accept` names, and what changed.
#[derive(Debug)]
pub struct Updated {
    pub entries: Vec<Entry>,
    pub changes: Vec<(String, String, Change)>,
}

/// Brings a scope's record up to date with its translations.
///
/// A translation with no line, or reworded since its line, is recorded as
/// made from today's default wording (a translation reworded to match a
/// changed default is the one thing `update` can tell was updated). One
/// made from wording that has changed and not reworded stays stale, so the
/// error stays until someone translates it again. Accepting a locale
/// records the acceptance of everything of its that is not stale.
pub fn updated(standings: &Standings, accept: Option<&str>) -> Updated {
    let mut entries = Vec::new();
    let mut changes = Vec::new();
    for standing in &standings.list {
        let mut change = None;
        let mut entry = match &standing.recorded {
            None => {
                change = Some(Change::Recorded);
                fresh(standing)
            }
            Some(recorded) if recorded.wording != standing.wording_hash => {
                change = Some(Change::Reworded);
                fresh(standing)
            }
            Some(recorded) => {
                if recorded.from != standing.default_hash {
                    change = Some(Change::StillStale);
                }
                recorded.clone()
            }
        };
        if accept == Some(standing.tag.as_str()) {
            if entry.from != standing.default_hash {
                change = Some(Change::StillStale);
            } else if !entry.accepted {
                entry.accepted = true;
                change = Some(Change::Accepted);
            }
        }
        if let Some(change) = change {
            changes.push((standing.tag.clone(), standing.member.clone(), change));
        }
        entries.push(entry);
    }
    for gone in &standings.record {
        if !entries
            .iter()
            .any(|entry| entry.locale == gone.locale && entry.member == gone.member)
        {
            changes.push((gone.locale.clone(), gone.member.clone(), Change::Removed));
        }
    }
    entries.sort_by(|a, b| (&a.locale, &a.member).cmp(&(&b.locale, &b.member)));
    changes.sort_by(|a, b| (&a.0, &a.1).cmp(&(&b.0, &b.1)));
    Updated { entries, changes }
}

fn fresh(standing: &Standing) -> Entry {
    Entry {
        locale: standing.tag.clone(),
        member: standing.member.clone(),
        from: standing.default_hash.clone(),
        wording: standing.wording_hash.clone(),
        accepted: false,
    }
}
