//! Who can do what, `access.jadpo_record` (areas 9 and 18, chunk A8): a
//! view of the permissions report that `jadpo check` keeps at the root
//! beside `api/`, so a change that widens access is a diff in the pull
//! request and an acceptance has a before side to judge it against.
//!
//! It holds what a widening is read from: the tenant, each entity's grants
//! and where its records belong, each field's own narrower grants, the
//! actions and queries listed under `actions:`, every decline of a rule
//! the catalogue marks as a security rule, and the sign-in settings that
//! have a limit (area 8, "Magic links"). Routes made public are read from
//! the API record, which says so already.
//!
//! ```text
//! // Generated by Jadpo from who can do what; update it with `jadpo records update`, never by hand.
//! record access 1
//!
//! tenant Company
//!
//! entity work.Project
//!     create CompanyRole.editor
//!     read CompanyRole.viewer
//!     tenant company_id
//!
//! field work.Project.budget
//!     read CompanyRole.editor
//!
//! action todos.transfer_todo
//!     who Todo.owner_id
//! ```

use jadpo_db::record::{self as format, Entry};
use jadpo_db::{Db, Project};

use crate::lookups::Lookup;
use crate::policy::{Effect, FieldPolicy};

/// The record's file, at the root.
pub const PATH: &str = format::ACCESS_FILE;

/// A field's own list that lets nobody in, written so it reads apart from
/// a field that follows its record's list.
pub const NOBODY: &str = "nobody";

/// The sign-in settings whose loosening past a limit needs a person (area
/// 8, "Settings"), each with its limit as the record writes it.
pub fn sign_in_limits() -> [(&'static str, String); 3] {
    use jadpo_std::http as h;
    [
        ("code_attempts", h::MAGIC_LINK_CODE_ATTEMPTS_MAX.to_string()),
        (
            "expires_after",
            jadpo_std::Dur {
                millis: i128::from(h::MAGIC_LINK_EXPIRES_MAX_MS),
            }
            .to_string(),
        ),
        (
            "failed_codes_per_day",
            h::MAGIC_LINK_FAILED_CODES_PER_DAY_MAX.to_string(),
        ),
    ]
}

/// The record's text: `Some(None)` when there is nothing to record,
/// `None` while policy has errors, so it can't be worked out.
#[salsa::tracked(returns(ref))]
pub fn record_text(db: &dyn Db, project: Project) -> Option<Option<String>> {
    if project.layout(db) != jadpo_db::Layout::Project || !crate::policy::policy_clean(db, project)
    {
        return None;
    }
    let entries = entries(db, project);
    if entries.is_empty() {
        return Some(None);
    }
    Some(Some(format::write(
        &format::ACCESS,
        format::ACCESS_FROM,
        &entries,
    )))
}

fn entries(db: &dyn Db, project: Project) -> Vec<Entry> {
    let access = crate::policy::access(db, project);
    let lookup = Lookup::new(db, project);
    let mut out = Vec::new();
    if let Some(tenant) = &access.root.tenant {
        out.push(Entry::new(format!("tenant {tenant}")));
    }
    let mut entities: Vec<(String, &crate::policy::EntityPolicy)> = access
        .entities
        .values()
        .map(|policy| {
            (
                crate::policy::report::qualified(&lookup, &policy.entity),
                policy,
            )
        })
        .collect();
    entities.sort_by(|a, b| a.0.cmp(&b.0));
    for (name, policy) in entities {
        let mut entry = Entry::new(format!("entity {name}"));
        for effect in Effect::ALL {
            for who in sorted(policy.lists.get(&effect).map(|list| &list.written)) {
                entry.push(format!("{} {who}", effect.word()));
            }
        }
        if access.root.tenant.is_some() {
            match &policy.tenancy {
                Some(tenancy) => entry.push(format!("tenant {}", tenancy.via)),
                None => entry.push("shared"),
            }
        }
        out.push(entry);
        let mut fields: Vec<&FieldPolicy> = policy.fields.iter().collect();
        fields.sort_by(|a, b| a.field.cmp(&b.field));
        for field in fields {
            let mut entry = Entry::new(format!("field {name}.{}", field.field));
            if field.server_only {
                entry.push("server_only");
            } else {
                for effect in FieldPolicy::EFFECTS {
                    let Some(list) = field.lists.get(&effect) else {
                        continue;
                    };
                    let who = sorted(Some(&list.written));
                    if who.is_empty() {
                        entry.push(format!("{} {NOBODY}", effect.word()));
                    }
                    for who in who {
                        entry.push(format!("{} {who}", effect.word()));
                    }
                }
            }
            out.push(entry);
        }
    }
    for (word, lines) in [
        ("action", &access.root.actions),
        ("query", &access.root.queries),
    ] {
        let mut lines: Vec<&crate::policy::ActionGrants> = lines.iter().collect();
        lines.sort_by(|a, b| a.written.cmp(&b.written));
        for line in lines {
            let mut entry = Entry::new(format!("{word} {}", line.written));
            for who in sorted(Some(&line.written_who)) {
                entry.push(format!("who {who}"));
            }
            out.push(entry);
        }
    }
    // How each role must be signed in to (chunk A10): any change to one,
    // or a role's line added or removed, needs a person.
    for (role, requirement) in crate::policy::report::role_requirements(&lookup, access) {
        let mut entry = Entry::new(format!("role {role}"));
        for line in requirement.lines() {
            entry.push(line);
        }
        out.push(entry);
    }
    let mut declined: Vec<String> = security_declines(db, project)
        .into_iter()
        .map(|(rule, subject)| format!("decline {rule} {subject}"))
        .collect();
    declined.sort();
    declined.dedup();
    out.extend(declined.into_iter().map(Entry::new));
    let identity = crate::identity::identity(db, project);
    if let Some(magic) = &identity.magic_link {
        let mut entry = Entry::new("sign_in magic_link");
        entry.push(format!("code_attempts: {}", magic.code_attempts));
        entry.push(format!(
            "expires_after: {}",
            jadpo_std::Dur {
                millis: i128::from(magic.expires_after_ms)
            }
        ));
        entry.push(format!(
            "failed_codes_per_day: {}",
            magic.failed_codes_per_day
        ));
        out.push(entry);
    }
    out
}

fn sorted(list: Option<&Vec<String>>) -> Vec<String> {
    let mut out: Vec<String> = list.cloned().unwrap_or_default();
    out.sort();
    out.dedup();
    out
}

/// Each `decline` line naming a rule the catalogue marks as a security
/// rule, as the rule and what it declines on: the declaration's name with
/// its domain (`lending.borrow_book`), as `actions:` names an action.
pub fn security_declines(db: &dyn Db, project: Project) -> Vec<(String, String)> {
    crate::declines::declines(db, project)
        .into_iter()
        .filter(|decline| jadpo_diag::find(&decline.rule).is_some_and(|rule| rule.security))
        .filter_map(|decline| {
            let subject = decline.subject.clone()?;
            Some((decline.rule.clone(), qualify(&decline.path, &subject)))
        })
        .collect()
}

/// `subject` with the domain of the file at `path` before it.
pub fn qualify(path: &str, subject: &str) -> String {
    match path
        .strip_prefix("domains/")
        .and_then(|rest| rest.split('/').next())
    {
        Some(domain) => format!("{domain}.{subject}"),
        None => subject.to_string(),
    }
}
