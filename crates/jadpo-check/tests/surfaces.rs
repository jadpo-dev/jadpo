fn surface_of(
    files: &[(&str, &str)],
    records: &[(&str, &str)],
    folder: &str,
    version: Option<&str>,
) -> Option<String> {
    let db = Database::default();
    let project = project_with_records(&db, Layout::Project, files, records);
    let problems = jadpo_check::check(&db, project);
    assert!(problems.is_empty(), "{problems:#?}");
    surface::text(&db, project, folder, version)
}

const GUIDE: (&str, &str) = (
    "shared/providers/postcodes/v2/GUIDE.md",
    "# Postcodes\n\nParse first.\n",
);

#[test]
fn a_library_packages_surface_lists_its_public_declarations() {
    let text = surface_of(
        &library(),
        &[GUIDE],
        "shared/providers/postcodes/v2",
        Some("2.1.0"),
    )
    .expect("a surface");
    assert_eq!(text, format!("{HEADER}{LIBRARY_SURFACE}"));
}

#[test]
fn a_surface_without_a_version_leaves_the_line_out() {
    let text =
        surface_of(&library(), &[], "shared/providers/postcodes/v2", None).expect("a surface");
    let expected = format!("{HEADER}{LIBRARY_SURFACE}")
        .replace("    version 2.1.0\n", "")
        .replace("    guide GUIDE.md\n", "");
    assert_eq!(text, expected);
}

