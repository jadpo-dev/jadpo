#[test]
fn every_public_declaration_needs_a_description_to_be_published() {
    let mut files = library();
    files.push((
        "shared/providers/postcodes/v2/types/outward_code.jadpo",
        "public type OutwardCode = Text {
    max_length: 4
}
",
    ));
    files.push((
        "shared/providers/postcodes/v2/libraries/outward.jadpo",
        "public library outward {
    function of(postcode: UkPostcode) -> OutwardCode {
        return \"SW1A\"
    }
}
",
    ));
    let db = Database::default();
    let project = project_with_records(&db, Layout::Project, &files, &[]);
    let found: Vec<String> = publishing::undescribed(&db, project, "shared/providers/postcodes/v2")
        .iter()
        .map(|d| {
            let path = d.primary.as_ref().map_or("", |l| l.span.path.as_str());
            format!("{path} {}: {}", d.rule.id, d.message)
        })
        .collect();
    assert_eq!(
        found,
        [
            "shared/providers/postcodes/v2/libraries/outward.jadpo publish.description_missing: Public library `outward` has no description",
            "shared/providers/postcodes/v2/libraries/outward.jadpo publish.description_missing: Function `outward.of` has no description",
            "shared/providers/postcodes/v2/types/outward_code.jadpo publish.description_missing: Public type `OutwardCode` has no description",
        ]
    );
}

#[test]
fn a_packages_public_type_is_held_to_the_standard_types_and_its_own_are_not() {
    let mut files = library();
    files.push((
        "shared/providers/postcodes/v2/types/geo_point.jadpo",
        "/// Where a postcode's centre is.
public type GeoPoint = Object {
    lat: Decimal
    lng: Decimal
}
",
    ));
    files.push((
        "shared/providers/postcodes/v2/types/sent_point.jadpo",
        "/// The pair the lookup service sends, decoded before it leaves.
type SentPoint = Object {
    lat: Decimal
    lng: Decimal
}
",
    ));
    let db = Database::default();
    let project = project_with_records(&db, Layout::Project, &files, &[]);
    // `SentPoint` isn't used here: what matters is that it isn't the
    // standard `Point` under another name.
    let problems: Vec<_> = jadpo_check::check(&db, project)
        .into_iter()
        .filter(|d| d.rule.id != "layout.unused_declaration")
        .collect();
    assert_eq!(problems.len(), 1, "{problems:#?}");
    let problem = &problems[0];
    assert_eq!(problem.rule.id, "type.standard_exists");
    assert_eq!(
        problem.message,
        "`GeoPoint` is the standard `Point` under another name"
    );
    assert_eq!(
        problem.reason.as_deref(),
        Some(
            "`GeoPoint` has only a latitude (`lat`) and a longitude (`lng`), which is the standard `Point`. Packages that each declare their own disagree on order and on names, and an app has to convert between them."
        )
    );
    assert_eq!(
        problem.next.as_ref().map(|next| next.text.as_str()),
        Some(
            "Use `Point` in the package's public types, converting at the edge with `geo.from_lat_lng` or `geo.from_lng_lat` where the provider sends a pair, or write `decline type.standard_exists: \"<why>\"` above it if this is deliberate"
        )
    );
}

fn entries(text: &str) -> String {
    format!("{HEADER}{text}")
}

const BEFORE: &str = "
package Postcodes.v2
    /// UK postcodes.
    file package.jadpo
    kind library
    version 2.0.3
    licence mit
    jadpo 1.0

function uk.parse
    /// Reads a UK postcode.
    file libraries/uk.jadpo
    signature (written: Text) -> UkPostcode
    fails InvalidPostcode

type UkPostcode = Text
    /// A UK postcode.
    file types/uk_postcode.jadpo
    max_length: 8
";

#[test]
fn a_first_release_is_the_major_its_label_names() {
    let now = entries(BEFORE);
    assert_eq!(
        publishing::version("v2", None, &now),
        Ok(Bump {
            version: "2.0.0".to_string(),
            since: None,
            changes: Vec::new(),
        })
    );
    assert_eq!(
        publishing::version("v2024_06_20", None, &now).map(|bump| bump.version),
        Ok("1.0.0".to_string())
    );
    assert_eq!(
        publishing::version("v0", None, &now).map(|bump| bump.version),
        Ok("0.1.0".to_string())
    );
}

#[test]
fn a_surface_with_only_new_declarations_is_a_minor_release() {
    let before = entries(BEFORE);
    let now = entries(&format!(
        "{BEFORE}
type OutwardCode = Text
    /// The first half of a postcode.
    file types/outward_code.jadpo
    max_length: 4
"
    ));
    let bump = publishing::version("v2", Some(("2.0.3", &before)), &now).expect("allowed");
    assert_eq!(bump.version, "2.1.0");
    assert_eq!(bump.since.as_deref(), Some("2.0.3"));
    assert_eq!(
        bump.changes,
        [("added".to_string(), "type OutwardCode".to_string())]
    );
}

#[test]
fn a_surface_whose_descriptions_alone_changed_is_a_patch() {
    let before = entries(BEFORE);
    let now = entries(&BEFORE.replace("/// Reads a UK postcode.", "/// Reads a postcode."));
    let bump = publishing::version("v2", Some(("2.0.3", &before)), &now).expect("allowed");
    assert_eq!(bump.version, "2.0.4");
    assert!(bump.changes.is_empty(), "{:?}", bump.changes);
}

#[test]
fn a_breaking_change_is_refused_within_a_major_version() {
    let before = entries(BEFORE);
    let new_failure = entries(&BEFORE.replace(
        "    fails InvalidPostcode\n",
        "    fails InvalidPostcode\n    fails PostcodeRetired\n",
    ));
    let removed = entries(&BEFORE.replace(
        "\ntype UkPostcode = Text\n    /// A UK postcode.\n    file types/uk_postcode.jadpo\n    max_length: 8\n",
        "",
    ));
    assert_eq!(
        publishing::version("v2", Some(("2.0.3", &before)), &new_failure),
        Err(vec![(
            "changed".to_string(),
            "function uk.parse".to_string()
        )])
    );
    assert_eq!(
        publishing::version("v2", Some(("2.0.3", &before)), &removed),
        Err(vec![("removed".to_string(), "type UkPostcode".to_string())])
    );
}
