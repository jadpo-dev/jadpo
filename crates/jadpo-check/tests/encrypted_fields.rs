#[test]
fn a_key_held_as_data_goes_nowhere_else() {
    for body in [
        // Handed back, or passed to code of the app's own.
        "action f(device: Device) -> EncryptionKey {\n    return device.device_key\n}\n",
        "action f() -> EncryptionKey {\n    return crypto.new_key(as: EncryptionKey)\n}\n",
        "function sealer(key: EncryptionKey) -> Shown {\n    return \"x\"\n}\n\nfunction f(device: Device) -> Shown {\n    return sealer(device.device_key)\n}\n",
        // Read as text or bytes.
        "function f(device: Device) -> Shown {\n    return Shown(text.from(device.device_key))\n}\n",
        "function f(device: Device) -> KeptDigest {\n    return KeptDigest(hash.sha256(device.device_key))\n}\n",
        // Compared.
        "function f(device: Device, other: Device) -> Same {\n    return Same(device.device_key == other.device_key)\n}\n",
        // Written into something else.
        "type Held = Object {\n    key: EncryptionKey\n}\n\nfunction f(device: Device) -> Held {\n    return Held {\n        key: device.device_key\n    }\n}\n",
        // As anything but a `crypto` call's `key:`.
        "action f(device: Device) -> Sealed {\n    return Sealed(crypto.encrypt(device.device_key, key: device.device_key, context: \"c\"))\n}\n",
        "action f(device: Device) -> Sealed {\n    return Sealed(crypto.encrypt(\"x\", key: device.device_key, context: device.device_key))\n}\n",
    ] {
        let found = rules(&format!("{DEVICE}{body}"));
        assert!(
            found.contains(&"type.key_as_value".to_string()),
            "{body}: {found:?}"
        );
    }
}

