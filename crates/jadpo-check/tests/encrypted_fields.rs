#[test]
fn a_stored_secret_still_goes_nowhere_else() {
    let entity = consultation("    authenticator: TotpSecret\n    recovery: SecretText\n");
    // A type that names the field holds what the field does.
    for declared in [
        "type Sent = Output {\n    authenticator: Consultation.authenticator\n}\n",
        "type Told = Event {\n    recovery: Consultation.recovery\n}\n",
        "type Refused = Failure {\n    kind: FailureKind.invalid_value\n    internal: {\n        recovery: Consultation.recovery\n    }\n}\n",
    ] {
        let found = rules(&format!("{entity}\n{declared}"));
        assert!(
            found.contains(&"type.secret_exposed".to_string()),
            "{declared}: {found:?}"
        );
    }
    for read in [
        "function written(consultation: Consultation) -> Shown {\n    return Shown(text.from(consultation.recovery))\n}\n",
        "function digest(consultation: Consultation) -> KeptDigest {\n    return KeptDigest(hash.sha256(consultation.authenticator))\n}\n",
    ] {
        let found = rules(&format!("{entity}\n{read}"));
        assert!(
            found.contains(&"type.secret_exposed".to_string()),
            "{read}: {found:?}"
        );
    }
}

