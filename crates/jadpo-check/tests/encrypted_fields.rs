#[test]
fn an_action_makes_a_key_and_stores_it_or_uses_it() {
    assert_eq!(
        rules(&format!(
            "{DEVICE}action enrol() -> Device {{\n    var device_key: EncryptionKey = crypto.new_key(as: EncryptionKey)\n    return Device.create {{\n        set: {{\n            device_key: device_key\n            backup_key: crypto.new_key(as: EncryptionKey)\n            signing_key: crypto.new_key(as: PrivateKey)\n        }}\n    }}\n}}\n\naction seal_with_a_new_key(note: ClinicalNote) -> Sealed {{\n    var made: EncryptionKey = crypto.new_key(as: EncryptionKey)\n    return Sealed(crypto.encrypt(note, key: made, context: \"note\"))\n}}\n\naction seal_for(device: Device, note: ClinicalNote) -> Sealed {{\n    return Sealed(crypto.encrypt(note, key: device.device_key, context: \"note\"))\n}}\n\nfunction sign_for(device: Device, note: ClinicalNote) -> Sealed {{\n    return Sealed(crypto.sign(note, key: device.signing_key))\n}}\n\nfunction public_for(device: Device) -> PublicKey {{\n    return crypto.public_key(key: device.signing_key)\n}}\n"
        )),
        CLEAN
    );
}

