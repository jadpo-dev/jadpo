#[test]
fn what_the_database_needs_to_read_cant_be_sealed() {
    for field in [
        // `encrypted:` takes `true` or `false`.
        "    notes: ClinicalNote {\n        encrypted: \"yes\"\n    }\n",
        // Generated by the database's clock, and compared by the purge.
        "    seen_at: Instant {\n        generated: Generated.on_create\n        encrypted: true\n    }\n",
        // A foreign key is a comparison.
        "    parent_id: Consultation.id? {\n        on_delete: OnDelete.cleared\n        encrypted: true\n    }\n",
    ] {
        assert_eq!(
            rules(&consultation(field)),
            ["data.encrypted_field_invalid"],
            "{field}"
        );
    }
    // Every record's `id` is what a sealed value is bound to.
    assert_eq!(
        rules(&format!(
            "entity Consultation {{\n    id: Uuid {{\n        encrypted: true\n    }}\n{POLICY}}}\n"
        )),
        ["data.encrypted_field_invalid"]
    );
    // A `File`'s bytes are in its store, and its column is a reference.
    let found = support::rules(
        Layout::Loose,
        &[(
            "main.jadpo",
            &format!(
                "{HEAD}{}",
                consultation(
                    "    letter: File {\n        store: letters\n        max_size: 5mb\n        encrypted: true\n    }\n"
                )
            ),
        )],
    );
    assert!(
        found.contains(&"data.encrypted_field_invalid".to_string()),
        "{found:?}"
    );
}

#[test]
