#[test]
fn a_secret_inside_a_structure_stays_refused() {
    // Kept only in a field of its own, so its column holds only sealed
    // bytes and nothing else is written around it.
    assert_eq!(
        rules(
            "type Held = Object {\n    code: TotpSecret\n}\n\nentity Consultation {\n    id: Uuid\n    held: Held\n\n    policy: {\n        create: [Access.public]\n        read: [Access.public]\n        update: [Access.public]\n        delete: [Access.public]\n    }\n}\n"
        ),
        ["type.secret_exposed"]
    );
    // A password, a token and the like are never stored, sealed or not.
    for field in [
        "    password: Password\n",
        "    password: Password {\n        encrypted: true\n    }\n",
        "    token: BearerToken {\n        encrypted: true\n    }\n",
    ] {
        assert_eq!(
            rules(&consultation(field)),
            ["type.secret_exposed"],
            "{field}"
        );
    }
}

