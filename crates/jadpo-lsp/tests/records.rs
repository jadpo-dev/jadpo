//! `jadpo lsp` serving records (area 18, "Records in git and in your
//! editor"): a record's errors on the record itself, followed as the
//! editor edits it, its outline, a fold for each entry and a link on each
//! file a fact points at.

use lsp_server::{Message, Notification};
use serde_json::{Value, json};

use crate::support::{ask, project, start, uri};

const API: &str = "api/main.jadpo_record";

const RECORD: &str = "// Generated by Jadpo from the routes of API main; update it with `jadpo api update`, never by hand.
record api 1

POST /memos
    authentication none
    input AddMemo (body)
    output MemoView
    status 200

GET /openapi.json
    generated openapi
    authentication none
    status 200

input AddMemo
    text: Text { max_length: 200 }

output MemoView
    text: Text { max_length: 200 }
";

const SURFACE: &str = "packages/acme_notes/v1/surface.jadpo_record";

const SURFACE_TEXT: &str = "// Generated by Jadpo from this package's code; update it with `jadpo package check`, never by hand.
record surface 1

package AcmeNotes.v1
    file package.jadpo
    version 1.0.0

function notes.shout
    file libraries/notes.jadpo
    file libraries/missing.jadpo
";

fn files(record: &str) -> Vec<(&'static str, String)> {
    vec![
        ("app.jadpo", "application {}\n".to_string()),
        (
            "policy.jadpo",
            "use memos\n\npolicy {\n    actions: {\n        memos.add_memo: [Access.public]\n    }\n}\n"
                .to_string(),
        ),
        (
            "domains/memos/types/memo.jadpo",
            "type Memo = Text {\n    max_length: 200\n}\n".to_string(),
        ),
        (
            "domains/memos/types/memo_view.jadpo",
            "use memos/types { Memo }\n\ntype MemoView = Output {\n    text: Memo\n}\n".to_string(),
        ),
        (
            "domains/memos/actions/add_memo.jadpo",
            "use memos/types { Memo, MemoView }\n\ntype AddMemo = Input {\n    text: Memo\n}\n\naction add_memo(input: AddMemo) -> MemoView {\n    return MemoView {\n        text: input.text\n    }\n}\n".to_string(),
        ),
        (
            "domains/memos/routes/memos.jadpo",
            "use memos/types { MemoView }\nuse memos/actions { AddMemo, add_memo }\n\nroutes Memos {\n    prefix: /memos\n\n    POST / {\n        authentication: RouteAuthentication.none\n        input: AddMemo\n        output: MemoView\n        run: add_memo(input)\n    }\n}\n".to_string(),
        ),
        (
            "access.jadpo_record",
            "// Generated by Jadpo from who can do what; update it with `jadpo records update`, never by hand.\nrecord access 1\n\naction memos.add_memo\n    who Access.public\n".to_string(),
        ),
        (API, record.to_string()),
    ]
}

fn root_of(name: &str, record: &str) -> std::path::PathBuf {
    let owned = files(record);
    let borrowed: Vec<(&str, &str)> = owned.iter().map(|(p, t)| (*p, t.as_str())).collect();
    project(name, &borrowed)
}

/// What each published file's diagnostics say, by URI.
fn published(messages: Vec<Message>) -> Vec<(String, Vec<Value>)> {
    messages
        .into_iter()
        .filter_map(|message| match message {
            Message::Notification(note) if note.method == "textDocument/publishDiagnostics" => {
                Some((
                    note.params["uri"].as_str().unwrap_or("").to_string(),
                    note.params["diagnostics"]
                        .as_array()
                        .cloned()
                        .unwrap_or_default(),
                ))
            }
            _ => None,
        })
        .collect()
}

fn notify(server: &mut jadpo_lsp::Server, method: &str, params: Value) {
    server.handle(Message::Notification(Notification::new(
        method.to_string(),
        params,
    )));
}

#[test]
fn a_records_errors_are_shown_on_it_and_follow_its_edits() {
    let edited = RECORD.replace(
        "    status 200\n\nGET",
        "    // Clients rely on 200.\n    status 200\n\nGET",
    );
    let root = root_of("lsp-records-errors", &edited);
    let mut server = start(&root, json!({}));
    let first = published(server.flush());
    let on_record: Vec<&(String, Vec<Value>)> = first
        .iter()
        .filter(|(u, _)| *u == uri(&root, API))
        .collect();
    assert_eq!(on_record.len(), 1, "{first:?}");
    let problems = &on_record[0].1;
    assert_eq!(problems.len(), 1, "{problems:?}");
    assert_eq!(problems[0]["code"], "record.edited");
    assert_eq!(problems[0]["range"]["start"]["line"], 7);
    // Opened and put right in the editor, before it is saved.
    notify(
        &mut server,
        "textDocument/didOpen",
        json!({"textDocument": {"uri": uri(&root, API), "languageId": "jadpo-record", "version": 1, "text": edited}}),
    );
    notify(
        &mut server,
        "textDocument/didChange",
        json!({"textDocument": {"uri": uri(&root, API), "version": 2}, "contentChanges": [{"text": RECORD}]}),
    );
    let cleared = published(server.flush());
    assert_eq!(cleared, vec![(uri(&root, API), Vec::new())]);
    // Closed unsaved: the disk is the text again.
    notify(
        &mut server,
        "textDocument/didClose",
        json!({"textDocument": {"uri": uri(&root, API)}}),
    );
    let again = published(server.flush());
    assert_eq!(again.len(), 1, "{again:?}");
    assert_eq!(again[0].1[0]["code"], "record.edited");
}

#[test]
fn a_record_has_an_outline_of_its_entries() {
    let root = root_of("lsp-records-outline", RECORD);
    let mut server = start(&root, json!({}));
    let symbols = ask(
        &mut server,
        "textDocument/documentSymbol",
        json!({"textDocument": {"uri": uri(&root, API)}}),
    );
    let outline: Vec<(String, u64, u64, Vec<String>)> = symbols
        .as_array()
        .expect("symbols")
        .iter()
        .map(|symbol| {
            (
                symbol["name"].as_str().unwrap_or("").to_string(),
                symbol["range"]["start"]["line"].as_u64().unwrap_or(99),
                symbol["range"]["end"]["line"].as_u64().unwrap_or(99),
                symbol["children"]
                    .as_array()
                    .into_iter()
                    .flatten()
                    .map(|child| child["name"].as_str().unwrap_or("").to_string())
                    .collect(),
            )
        })
        .collect();
    assert_eq!(
        outline,
        vec![
            ("POST /memos".to_string(), 3, 7, vec![]),
            ("GET /openapi.json".to_string(), 9, 12, vec![]),
            (
                "input AddMemo".to_string(),
                14,
                15,
                vec!["text".to_string()]
            ),
            (
                "output MemoView".to_string(),
                17,
                18,
                vec!["text".to_string()]
            ),
        ]
    );
}

#[test]
fn each_entry_with_members_folds() {
    let root = root_of("lsp-records-folds", RECORD);
    let mut server = start(&root, json!({}));
    let folds = ask(
        &mut server,
        "textDocument/foldingRange",
        json!({"textDocument": {"uri": uri(&root, API)}}),
    );
    let ranges: Vec<(u64, u64)> = folds
        .as_array()
        .expect("folds")
        .iter()
        .map(|fold| {
            (
                fold["startLine"].as_u64().unwrap_or(99),
                fold["endLine"].as_u64().unwrap_or(99),
            )
        })
        .collect();
    assert_eq!(ranges, vec![(3, 7), (9, 12), (14, 15), (17, 18)]);
}

#[test]
fn a_file_a_fact_names_is_a_link() {
    let mut owned = files(RECORD);
    owned.push((SURFACE, SURFACE_TEXT.to_string()));
    owned.push((
        "packages/acme_notes/v1/libraries/notes.jadpo",
        "library notes {}\n".to_string(),
    ));
    owned.push((
        "packages/acme_notes/v1/package.jadpo",
        "package {}\n".to_string(),
    ));
    let borrowed: Vec<(&str, &str)> = owned.iter().map(|(p, t)| (*p, t.as_str())).collect();
    let root = project("lsp-records-links", &borrowed);
    let mut server = start(&root, json!({}));
    let links = ask(
        &mut server,
        "textDocument/documentLink",
        json!({"textDocument": {"uri": uri(&root, SURFACE)}}),
    );
    let found: Vec<(u64, u64, u64, String)> = links
        .as_array()
        .expect("links")
        .iter()
        .map(|link| {
            (
                link["range"]["start"]["line"].as_u64().unwrap_or(99),
                link["range"]["start"]["character"].as_u64().unwrap_or(99),
                link["range"]["end"]["character"].as_u64().unwrap_or(99),
                link["target"].as_str().unwrap_or("").to_string(),
            )
        })
        .collect();
    // A file that isn't there is no link.
    assert_eq!(
        found,
        vec![
            (4, 9, 22, uri(&root, "packages/acme_notes/v1/package.jadpo")),
            (
                8,
                9,
                30,
                uri(&root, "packages/acme_notes/v1/libraries/notes.jadpo")
            ),
        ]
    );
}

#[test]
fn the_server_says_it_serves_outlines_folds_and_links() {
    let root = root_of("lsp-records-capabilities", RECORD);
    let params = serde_json::from_value(json!({
        "processId": null,
        "rootUri": format!("file://{}", root.display()),
        "capabilities": {},
    }))
    .expect("params");
    let (_, result) = jadpo_lsp::Server::initialize(&params, &root);
    let capabilities = serde_json::to_value(result.capabilities).expect("JSON");
    assert_eq!(capabilities["documentSymbolProvider"], true);
    assert_eq!(capabilities["foldingRangeProvider"], true);
    assert_eq!(
        capabilities["documentLinkProvider"]["resolveProvider"],
        false
    );
}
