/// The planning app in `folder(name)`, its first migration and its records
/// written.
fn planning(name: &str) -> PathBuf {
    let root = folder(name);
    for (path, text) in PLANNING {
        write(&root, path, text);
    }
    ok(&jadpo(&root, &["migrate", "new", "initial"]));
    ok(&jadpo(&root, &["records", "update"]));
    ok(&jadpo(&root, &["check"]));
    root
}

