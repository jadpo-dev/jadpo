/// Each call's seed, so each record made gets an id of its own.
static SEED: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(1);

/// What `name` gives on the interpreter with `args`.
pub(crate) fn interpreted(
    program: &Program,
    host: &Harness,
    name: &str,
    args: Vec<Value>,
) -> Value {
    let runtime = jadpo_host_native::Runtime::new().expect("runtime");
    let id = program.plan().find(name).expect("the callable");
    let outcome = runtime.block_on(async {
        let env = Env {
            seed: Some(SEED.fetch_add(1, std::sync::atomic::Ordering::Relaxed)),
            clock: Clock::TEST,
        };
        let mut ctx = Ctx::of(program, host, env);
        program.run(&mut ctx, id, args).await
    });
    match outcome {
        Outcome::Value(value) => value,
        other => panic!("{name}: {other:?}"),
    }
}

/// The compiled executor on `program`'s plan, as generated code holds it:
/// a query is read through the runtime's one read path from the plan's
/// canonical bytes, which is all a compiled query's site calls.
pub(crate) fn compiled(program: &Program) -> jadpo_runtime::compiled::Program {
    use jadpo_runtime::compiled::{Code, Shared};
    let bytes = program
        .plan()
        .runtime()
        .encode_deployable()
        .expect("the plan's bytes");
    let code: &'static Code = Box::leak(Box::new(Code {
        plan: Box::leak(bytes.into_boxed_slice()),
        places: &[],
        callable: |_| None,
        row: |_, _| None,
        routes: |_| None,
        shared: Box::leak(Box::new(Shared::new())),
    }));
    jadpo_runtime::compiled::Program::new(code).expect("the plan decodes")
}

/// The project's one query, read on the compiled executor.
pub(crate) fn compiled_query(program: &jadpo_runtime::compiled::Program, host: &Harness) -> Value {
    let runtime = jadpo_host_native::Runtime::new().expect("runtime");
    assert_eq!(program.runtime().sites.queries.len(), 1);
    let ran = runtime.block_on(async {
        let env = Env {
            seed: Some(1),
            clock: Clock::TEST,
        };
        let mut ctx = Ctx::of(program, host, env);
        jadpo_runtime::compiled::query(&mut ctx, program, 0, &[], 0).await
    });
    ran.unwrap_or_else(|stop| panic!("the compiled query stopped: {stop:?}"))
}

/// Each record's `field`, in the list's order.
pub(crate) fn column(list: &Value, field: &str) -> Vec<Value> {
    let Value::List(items) = list else {
        panic!("not a list: {list:?}");
    };
    items
        .iter()
        .map(|item| match item {
            Value::Record(record) => record
                .get(field)
                .cloned()
                .unwrap_or_else(|| panic!("no `{field}` in {record:?}")),
            other => panic!("not a record: {other:?}"),
        })
        .collect()
}

#[test]
fn renaming_a_stored_field_keeps_its_rows_on_both_executors() {
    if !jadpo_test::live() {
        return;
    }
    let root = planning("rows");
    let server = jadpo_test::database::server().unwrap_or_else(|e| panic!("{e}"));
    let url = server.create_database("rename_rows").expect("database");
    ok(&jadpo(&root, &["migrate", "apply", "--url", &url]));
    let host = Harness::postgres(&url).random_from(0);
    {
        let loaded = jadpo_db::load(&root);
        let program = Program::load(&loaded.db, loaded.project).expect("the project checks");
        for (title, priority) in [("Post the letters", 1), ("Book the room", 3)] {
            interpreted(
                &program,
                &host,
                "add_todo",
                vec![Value::text(title), Value::Int(priority)],
            );
        }
    }
    ok(&jadpo(&root, &["rename", "Todo.priority", "importance"]));
    // Nothing to apply: the column is the one the rows are in.
    let status = jadpo(&root, &["migrate", "status", "--url", &url]);
    ok(&status);
    let loaded = jadpo_db::load(&root);
    let program = Program::load(&loaded.db, loaded.project).expect("the renamed project checks");
    let expected = vec![Value::Int(3), Value::Int(1)];
    let read = interpreted(&program, &host, "list_todos", Vec::new());
    assert_eq!(column(&read, "importance"), expected, "interpreted");
    assert_eq!(
        column(&read, "title"),
        vec![
            Value::text("Book the room"),
            Value::text("Post the letters")
        ]
    );
    let read = compiled_query(&compiled(&program), &host);
    assert_eq!(column(&read, "importance"), expected, "compiled");
    // And a row written after the rename lands in the same column.
    interpreted(
        &program,
        &host,
        "add_todo",
        vec![Value::text("Water the plants"), Value::Int(2)],
    );
    let read = compiled_query(&compiled(&program), &host);
    assert_eq!(
        column(&read, "importance"),
        vec![Value::Int(3), Value::Int(2), Value::Int(1)]
    );
}

