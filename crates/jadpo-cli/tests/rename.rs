//! `jadpo rename` (area 14, "Commands for looking into and changing
//! code"; area 18, "Stable identity"; area 5, "Migrations"): a declaration
//! or a field renamed at its declaration and everywhere it is used, its
//! file moved, the records it changes brought up to date and the identity
//! registry written, so a stored field keeps its column and its rows. A
//! name already in use is refused before anything changes, and a rename
//! whose result would have an error the project didn't have changes
//! nothing. A field renamed by hand is a removal and an addition, and the
//! removed one's decision names the command that keeps its column.
//!
//! The rows kept are read back on both executors against live PostgreSQL:
//! the interpreter, and the compiled executor from the plan's canonical
//! bytes, as generated code reads a query. The server is the one
//! `JADPO_TEST_DATABASE_URL` names or one started from the machine's
//! PostgreSQL tools; `JADPO_SKIP_POSTGRES=1` skips the live part.

