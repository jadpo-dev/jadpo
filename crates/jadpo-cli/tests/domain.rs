//! `jadpo domain rename`, `split` and `merge` (area 14, "Tools for agents";
//! area 1, "Domains"; area 18, "Stable identity" and "Acceptances"): a
//! domain's files moved and every call into it updated, on a two-domain
//! app, with nothing about what the moved code does changed. Every key
//! the graph holds is the same after the move, so stored rows, deliveries
//! and the review still know each thing; `jadpo migrate new` finds nothing
//! to migrate; the only acceptance asked for is the one the move needs
//! (`DomainChange.renamed` for a rename, `DomainChange.created` for the
//! domain a split makes, none for a merge); and the app's tests pass as
//! before. Each refusal changes nothing.
//!
//! The rows kept are read back on both executors against live PostgreSQL,
//! as `jadpo rename`'s are; `JADPO_SKIP_POSTGRES=1` skips the live part.

