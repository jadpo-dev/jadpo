#[test]
fn a_split_across_references_is_refused_naming_the_part_that_would_move() {
    let root = app("seam");
    let before = tree(&root);
    let output = jadpo(&root, &["domain", "split", "planning", "tasks", "Todo"]);
    assert_eq!(output.code, 2, "{}", output.stdout);
    assert_eq!(output.stdout, "");
    assert_eq!(
        output.stderr,
        "error: What moves and what stays in `planning` reference each other
  reason: A domain splits only where nothing references across it: `TodoAdded` uses `Todo`, `Todo` uses `TodoTitle`, `a_todo` uses `Todo` and 3 more.
  next: Move what they reach too: `jadpo domain split planning tasks Todo TodoAdded TodoTitle a_todo add_todo` (agent)
  rule: cli.domain_arguments
  help: https://jadpo.dev/docs/errors/cli.domain_arguments
"
    );
    // Naming what reaches the notes too leaves no seam at all.
    let whole = jadpo(
        &root,
        &[
            "domain",
            "split",
            "planning",
            "tasks",
            "Todo",
            "TodoAdded",
            "TodoTitle",
            "a_todo",
            "add_todo",
            "Note",
            "add_note",
            "all_notes",
            "list_notes",
        ],
    );
    assert_eq!(whole.code, 2);
    assert!(
        whole
            .stderr
            .starts_with("error: Everything in `planning` would move\n"),
        "{}",
        whole.stderr
    );
    assert_eq!(tree(&root), before, "a refused split changes nothing");
}

