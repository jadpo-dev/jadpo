/// The app in `folder(name)`, its first migration and records written and
/// committed on `main`, then on a branch of its own, so `jadpo check`
/// judges the move against the commit before it.
fn app(name: &str) -> PathBuf {
    let root = folder(name);
    for (path, text) in APP {
        write(&root, path, text);
    }
    ok(&jadpo(&root, &["migrate", "new", "initial"]));
    ok(&jadpo(&root, &["records", "update"]));
    ok(&jadpo(&root, &["check"]));
    git(&root, &["init", "-q"]);
    git(&root, &["add", "-A"]);
    git(&root, &["commit", "-q", "-m", "The app"]);
    git(&root, &["checkout", "-q", "-b", "move"]);
    root
}

/// What stays true of the app after a move: the same keys, but for the
/// domain a split adds or a merge takes away (`domain`, with `+` or `-`);
/// nothing to migrate; its formatting; and its tests passing on a live
/// database.
fn unchanged(root: &Path, before: &BTreeSet<String>, domain: Option<(char, &str)>) {
    let mut expected = before.clone();
    match domain {
        Some(('+', name)) => {
            expected.insert(format!("domain {name}"));
        }
        Some((_, name)) => {
            expected.remove(&format!("domain {name}"));
        }
        None => {}
    }
    assert_eq!(keys(root), expected, "every key stays as it was");
    let migrate = jadpo(root, &["migrate", "new", "after_move"]);
    ok(&migrate);
    assert!(
        migrate.stdout.starts_with("Nothing to migrate"),
        "{}",
        migrate.stdout
    );
    ok(&jadpo(root, &["fmt", "--check"]));
    if jadpo_test::live() {
        let tested = jadpo(root, &["test"]);
        ok(&tested);
        assert!(tested.stdout.contains("4 passed"), "{}", tested.stdout);
    }
}

/// Lists `needs` (`subject: Kind.change`) in a new acceptance with a
/// reason, as a person writes it, so `jadpo check` passes.
fn accept(root: &Path, purpose: &str, needs: &[&str]) {
    let check = jadpo(root, &["check"]);
    assert_eq!(check.code, 1, "{}", check.stdout);
    for need in needs {
        assert!(check.stdout.contains(need), "{need}: {}", check.stdout);
    }
    assert_eq!(
        check.stdout.matches("rule: acceptance.missing").count(),
        needs.len(),
        "only the move's acceptance is asked for: {}",
        check.stdout
    );
    ok(&jadpo(root, &["acceptance", "new", purpose]));
    let folder = root.join("acceptances");
    let file = fs::read_dir(&folder)
        .expect("acceptances/")
        .map(|entry| entry.expect("an entry").path())
        .find(|path| path.to_string_lossy().contains(purpose))
        .expect("the drafted acceptance");
    let text = fs::read_to_string(&file).expect("the draft");
    for need in needs {
        assert!(text.contains(need), "{need}: {text}");
    }
    let reasoned = text.replacen(
        "acceptance {",
        "/// The domain's new shape matches how the team talks about the work.\nacceptance {",
        1,
    );
    let reasoned = reasoned
        .lines()
        .filter(|line| !line.starts_with("///") || line.contains("the team talks"))
        .collect::<Vec<_>>()
        .join("\n")
        + "\n";
    fs::write(&file, reasoned).expect("the reason");
    ok(&jadpo(root, &["check"]));
}

#[test]
fn a_domain_renamed_moves_its_folder_and_every_call_and_keeps_every_identity() {
    let root = app("rename");
    let before = keys(&root);
    let output = jadpo(&root, &["domain", "rename", "planning", "plans"]);
    assert_eq!(output.stderr, "");
    assert_eq!(
        output.stdout,
        "  domains/planning
    - planning         folder of 12 files, renamed plans

  domains/plans
    + plans            folder, was planning

  domains/reminders/actions/remind.jadpo
    ~ line 7           plans, was planning

  domains/reminders/actions/remind.test.jadpo
    ~ line 5           plans, was planning

  tests/planning_and_reminders.test.jadpo
    ~ line 6           plans, was planning

  access.jadpo_record
    ~ record           brought up to date

  domains/plans/events/events.jadpo_record
    ~ record           brought up to date

  database/identities.jadpo_record
    + domain planning  now plans

Renamed domain planning to plans
    kept  tables note, todo

next: jadpo check  lists the acceptance a renamed domain needs
"
    );
    ok(&output);
    assert!(!root.join("domains/planning").exists());
    assert_eq!(
        read(&root, "domains/plans/actions/add_todo.jadpo"),
        "use plans/entities { Todo }\nuse plans/events { TodoAdded }\n\n/// Adds a todo.\npublic action add_todo(title: Todo.title) -> Todo {\n    var todo: Todo = Todo.create {\n        set: {\n            title: title\n            done: false\n        }\n    }\n    emit TodoAdded {\n        todo_id: todo.id\n    }\n    return todo\n}\n"
    );
    assert_eq!(
        read(&root, "domains/reminders/actions/remind.jadpo"),
        "use plans/entities { Todo }\nuse reminders/types { Reminder }\nuse plans\n\n/// Adds a todo and says how its reminder reads.\npublic action remind(title: Todo.title) -> Reminder {\n    var todo: Todo = plans.add_todo(title)\n    return Reminder {\n        line: \"Remember: \" + todo.title\n    }\n}\n"
    );
    let scenario = read(&root, "tests/planning_and_reminders.test.jadpo");
    assert!(
        scenario.contains("reminders.remind(plans.a_todo())"),
        "{scenario}"
    );
    // One line: the domain's types, events and functions follow it.
    assert_eq!(
        read(&root, "database/identities.jadpo_record"),
        format!("{REGISTRY_HEADER}\ndomain planning -> plans\n")
    );
    assert!(read(&root, "access.jadpo_record").contains("entity plans.Todo\n"));
    assert!(
        read(&root, "domains/plans/events/events.jadpo_record")
            .starts_with("// Generated by Jadpo from the events of domain plans;")
    );
    unchanged(&root, &before, None);
    // A renamed domain reads as renamed, not as one created, and needs a
    // person, as a new one does; its events and grants read as kept.
    accept(&root, "rename_planning", &["plans: DomainChange.renamed"]);

    // Renamed again, the line changes; back to its born name, it goes.
    ok(&jadpo(&root, &["domain", "rename", "plans", "agenda"]));
    assert_eq!(
        read(&root, "database/identities.jadpo_record"),
        format!("{REGISTRY_HEADER}\ndomain planning -> agenda\n")
    );
    let back = jadpo(&root, &["domain", "rename", "agenda", "planning"]);
    ok(&back);
    assert!(
        back.stdout.contains(
            "  database/identities.jadpo_record\n    - domain planning  back to its born name\n"
        ),
        "{}",
        back.stdout
    );
    assert_eq!(
        read(&root, "database/identities.jadpo_record"),
        REGISTRY_HEADER
    );
    assert_eq!(keys(&root), before);
}

