//! Generated records (area 18, chunk 7.0): `jadpo records` lists every
//! record by the command that writes it, with its state; `jadpo records
//! update` brings them all up to date, moving the API record and the
//! identity registry from their old names and sorting a ledger a merge left
//! out of order; `jadpo check` fails on a record out of date, edited by
//! hand or written by a newer Jadpo; the OpenAPI version is a hash of the
//! record; and `jadpo.lock` is a ledger in the same format.

use std::path::{Path, PathBuf};

use jadpo_cli::{Output, run};
use jadpo_term::Environment;

use crate::http::tempdir;

const FILES: &[(&str, &str)] = &[
    ("app.jadpo", "application {}\n"),
    (
        "policy.jadpo",
        "use memos\n\npolicy {\n    actions: {\n        memos.add_memo: [Access.public]\n    }\n}\n",
    ),
    (
        "domains/memos/types/memo.jadpo",
        "type Memo = Text {\n    max_length: 200\n}\n",
    ),
    (
        "domains/memos/types/memo_view.jadpo",
        "use memos/types { Memo }\n\ntype MemoView = Output {\n    text: Memo\n}\n",
    ),
    (
        "domains/memos/actions/add_memo.jadpo",
        "use memos/types { Memo, MemoView }\n\ntype AddMemo = Input {\n    text: Memo\n}\n\naction add_memo(input: AddMemo) -> MemoView {\n    return MemoView {\n        text: input.text\n    }\n}\n",
    ),
    (
        "domains/memos/routes/memos.jadpo",
        "use memos/types { MemoView }\nuse memos/actions { AddMemo, add_memo }\n\nroutes Memos {\n    prefix: /memos\n\n    POST / {\n        authentication: RouteAuthentication.none\n        input: AddMemo\n        output: MemoView\n        run: add_memo(input)\n    }\n}\n",
    ),
];

/// The API record `jadpo api update` writes for [`FILES`].
const RECORD: &str = "// Generated by Jadpo from the routes of API main; update it with `jadpo api update`, never by hand.
record api 1

POST /memos
    authentication none
    input AddMemo (body)
    output MemoView
    status 200

input AddMemo
    text: Text { max_length: 200 }

output MemoView
    text: Text { max_length: 200 }
";

const IDENTITIES_HEADER: &str = "// Generated by Jadpo from renames and moves; update it with `jadpo rename`, `jadpo domain` or `jadpo fmt --layout`, never by hand.\nrecord identities 1\n";

fn write(root: &Path, path: &str, text: &str) {
    let path = root.join(path);
    std::fs::create_dir_all(path.parent().expect("parent")).expect("folders");
    std::fs::write(path, text).expect("write");
}

fn read(root: &Path, path: &str) -> String {
    std::fs::read_to_string(root.join(path)).expect("read")
}

fn jadpo_in(env: Environment, cwd: &Path, args: &[&str]) -> Output {
    let args: Vec<String> = args.iter().map(|arg| arg.to_string()).collect();
    run(&args, &env.with_cwd(cwd))
}

fn jadpo(cwd: &Path, args: &[&str]) -> Output {
    jadpo_in(Environment::empty(), cwd, args)
}

fn project(stem: &str) -> (tempdir::Dir, PathBuf) {
    let dir = tempdir::Dir::new(stem);
    let root = dir.path().join("memos");
    for (path, text) in FILES {
        write(&root, path, text);
    }
    (dir, root)
}

/// The text without the bold `NO_COLOR` keeps.
fn strip_bold(text: &str) -> String {
    text.replace("\x1b[1m", "").replace("\x1b[0m", "")
}

fn rules(output: &Output) -> Vec<String> {
    let document: serde_json::Value = serde_json::from_str(&output.stdout).expect("JSON");
    document["diagnostics"]
        .as_array()
        .expect("diagnostics")
        .iter()
        .map(|d| d["rule"].as_str().unwrap_or_default().to_string())
        .collect()
}

#[test]
fn api_update_writes_the_record_in_the_record_format() {
    let (_dir, root) = project("records-api");
    let missing = jadpo(&root, &["check", "--json"]);
    assert_eq!(
        rules(&missing),
        ["record.out_of_date"],
        "{}",
        missing.stdout
    );
    let updated = jadpo(&root, &["api", "update"]);
    assert_eq!(updated.code, 0, "{}", updated.stdout);
    assert_eq!(read(&root, "api/main.jadpo_record"), RECORD);
    let checked = jadpo(&root, &["check"]);
    assert_eq!(checked.code, 0, "{}", checked.stdout);
}

#[test]
fn the_openapi_version_is_a_hash_of_the_record() {
    let (_dir, root) = project("records-openapi");
    write(&root, "api/main.jadpo_record", RECORD);
    assert_eq!(jadpo(&root, &["check"]).code, 0);
    let document: serde_json::Value =
        serde_json::from_str(&read(&root, "build/openapi/main.json")).expect("JSON");
    let version = jadpo_check::routes::record::openapi_version(RECORD);
    assert_eq!(version.len(), 12);
    assert_eq!(document["info"]["version"], serde_json::json!(version));
    // A change to the record is a new version.
    let changed = RECORD.replace("status 200", "status 201");
    assert_ne!(
        jadpo_check::routes::record::openapi_version(&changed),
        version
    );
}

#[test]
fn records_lists_each_record_by_what_writes_it() {
    let (_dir, root) = project("records-list");
    write(&root, "api/main.jadpo_record", RECORD);
    write(
        &root,
        "database/identities.jadpo_record",
        &format!("{IDENTITIES_HEADER}\ntype memos.Memo -> Memo\n"),
    );
    let listed = jadpo(&root, &["records"]);
    assert_eq!(listed.code, 0, "{}", listed.stdout);
    assert_eq!(
        listed.stdout,
        "jadpo api update
  api/main.jadpo_record             up to date

jadpo rename, jadpo domain or jadpo fmt --layout
  database/identities.jadpo_record  up to date

records up to date: 2 records
"
    );
    // A route changed: the record is out of date, and the one command
    // that brings it up to date is next.
    write(
        &root,
        "api/main.jadpo_record",
        &RECORD.replace("status 200", "status 201"),
    );
    let rich = jadpo_in(
        Environment::empty()
            .with_terminals(true, true, true)
            .with_var("TERM", "xterm-256color")
            .with_var("NO_COLOR", "1"),
        &root,
        &["records"],
    );
    assert_eq!(rich.code, 1, "{}", rich.stdout);
    assert_eq!(
        strip_bold(&rich.stdout),
        "jadpo api update
✗ api/main.jadpo_record             out of date

jadpo rename, jadpo domain or jadpo fmt --layout
✓ database/identities.jadpo_record  up to date

✗ records out of date  1 out of date · 2 records

→ jadpo api update  brings api/main.jadpo_record up to date
"
    );
    let json = jadpo(&root, &["records", "--json"]);
    let document: serde_json::Value = serde_json::from_str(&json.stdout).expect("JSON");
    assert_eq!(
        document["data"]["records"][0],
        serde_json::json!({
            "path": "api/main.jadpo_record",
            "kind": "api",
            "written_by": "jadpo api update",
            "state": "out_of_date",
            "command": "jadpo api update",
        })
    );
    assert_eq!(rules(&json), ["record.out_of_date"]);
}

#[test]
fn a_hand_edit_is_an_error_naming_the_command() {
    let (_dir, root) = project("records-edited");
    write(
        &root,
        "api/main.jadpo_record",
        &RECORD.replace(
            "    status 200\n",
            "    status 200 // clients rely on this\n",
        ),
    );
    let checked = jadpo(&root, &["check"]);
    assert_eq!(checked.code, 1);
    assert!(
        checked.stdout.contains(
            "error: `api/main.jadpo_record` was edited by hand: a comment isn't part of a record\n"
        ),
        "{}",
        checked.stdout
    );
    assert!(
        checked
            .stdout
            .contains("next: Run `jadpo api update`, which writes it again (agent)"),
        "{}",
        checked.stdout
    );
    let listed = jadpo(&root, &["records"]);
    assert!(
        listed
            .stdout
            .contains("api/main.jadpo_record  edited by hand"),
        "{}",
        listed.stdout
    );
    assert_eq!(jadpo(&root, &["api", "update"]).code, 0);
    assert_eq!(read(&root, "api/main.jadpo_record"), RECORD);
}

#[test]
fn a_record_from_a_newer_jadpo_is_refused_not_overwritten() {
    let (_dir, root) = project("records-newer");
    let newer = "// Generated by Jadpo from renames and moves; update it with `jadpo rename`, `jadpo domain` or `jadpo fmt --layout`, never by hand.\nrecord identities 2\n\nentity Memo was Note\n";
    write(&root, "api/main.jadpo_record", RECORD);
    write(&root, "database/identities.jadpo_record", newer);
    let checked = jadpo(&root, &["check", "--json"]);
    assert_eq!(
        rules(&checked),
        ["record.format_newer"],
        "{}",
        checked.stdout
    );
    let update = jadpo(&root, &["records", "update"]);
    assert_eq!(update.code, 1, "{}", update.stdout);
    assert_eq!(read(&root, "database/identities.jadpo_record"), newer);
}

#[test]
fn records_update_moves_records_from_their_old_names() {
    let (_dir, root) = project("records-old-names");
    write(
        &root,
        "api/main.api",
        "// Written by `jadpo api update` from the routes; never edit it by hand.\n// `jadpo check` fails while it disagrees with them.\nversion: 3\n\nPOST /memos\n",
    );
    write(
        &root,
        "database/identities.json",
        "{\n  \"type Memo\": \"memos.Memo\"\n}\n",
    );
    let checked = jadpo(&root, &["check", "--json"]);
    assert_eq!(
        rules(&checked),
        ["record.out_of_date", "record.out_of_date"],
        "{}",
        checked.stdout
    );
    let listed = jadpo(&root, &["records"]);
    assert!(
        listed
            .stdout
            .contains("  api/main.api              old name\n"),
        "{}",
        listed.stdout
    );
    let updated = jadpo(&root, &["records", "update"]);
    assert_eq!(updated.code, 0, "{}", updated.stdout);
    assert_eq!(
        updated.stdout,
        "Wrote api/main.jadpo_record

Removed api/main.api

Wrote database/identities.jadpo_record

Removed database/identities.json

records updated: 2 written, 2 removed, 2 records

next: git diff  shows what changed, to commit with the code
"
    );
    assert_eq!(read(&root, "api/main.jadpo_record"), RECORD);
    assert_eq!(
        read(&root, "database/identities.jadpo_record"),
        format!("{IDENTITIES_HEADER}\ntype memos.Memo -> Memo\n")
    );
    assert!(!root.join("api/main.api").exists());
    assert!(!root.join("database/identities.json").exists());
    assert_eq!(jadpo(&root, &["check"]).code, 0);
}

#[test]
fn a_ledger_a_merge_left_out_of_order_is_sorted_by_records_update() {
    let (_dir, root) = project("records-union");
    write(&root, "api/main.jadpo_record", RECORD);
    // Two branches' lines, as git's `union` merge leaves them.
    write(
        &root,
        "database/identities.jadpo_record",
        &format!(
            "{IDENTITIES_HEADER}\ntype memos.Memo -> Memo\ntype memos.MemoView -> MemoView\ntype memos.AddMemo -> AddMemo\n"
        ),
    );
    let checked = jadpo(&root, &["check"]);
    assert!(
        checked.stdout.contains(
            "`database/identities.jadpo_record` was edited by hand: its lines aren't in the order Jadpo writes them"
        ),
        "{}",
        checked.stdout
    );
    assert!(
        checked
            .stdout
            .contains("next: Run `jadpo records update`, which writes it again (agent)"),
        "{}",
        checked.stdout
    );
    assert_eq!(jadpo(&root, &["records", "update"]).code, 0);
    assert_eq!(
        read(&root, "database/identities.jadpo_record"),
        format!(
            "{IDENTITIES_HEADER}\ntype memos.AddMemo -> AddMemo\ntype memos.Memo -> Memo\ntype memos.MemoView -> MemoView\n"
        )
    );
    // Two lines for one thing are left for a person.
    write(
        &root,
        "database/identities.jadpo_record",
        &format!("{IDENTITIES_HEADER}\ntype memos.Memo -> Memo\ntype memos.Memo -> Note\n"),
    );
    let checked = jadpo(&root, &["check"]);
    assert!(
        checked
            .stdout
            .contains("`type memos.Memo` is on lines 4 and 5"),
        "{}",
        checked.stdout
    );
    assert_eq!(jadpo(&root, &["records", "update"]).code, 1);
}

#[test]
fn the_lock_is_a_record_checked_like_the_rest() {
    let (_dir, root) = project("records-lock");
    write(&root, "api/main.jadpo_record", RECORD);
    // A link names a live checkout outside `packages/` (chunk 7.1), so the
    // lock needs no installed package beside it.
    let lock = "// Generated by Jadpo from the installed packages; update it with `jadpo package add`, `update` or `remove`, never by hand.\nrecord lock 1\n\npackage Postcodes.v2 link ../postcodes\n".to_string();
    write(&root, "jadpo.lock", &lock);
    // The linked checkout, which every check reads in its place (chunk
    // 7.1b2).
    write(
        root.parent().expect("the project's folder"),
        "postcodes/package.jadpo",
        "/// UK postcodes.\npackage Postcodes.v2 {\n    licence: Licence.mit\n    jadpo: \"1.0\"\n}\n",
    );
    let checked = jadpo(&root, &["check"]);
    assert_eq!(checked.code, 0, "{}", checked.stdout);
    let listed = jadpo(&root, &["records"]);
    assert!(
        listed
            .stdout
            .contains("jadpo package add, update or remove\n  jadpo.lock"),
        "{}",
        listed.stdout
    );
    write(
        &root,
        "jadpo.lock",
        &lock.replace("link ../postcodes", "link"),
    );
    let checked = jadpo(&root, &["check", "--json"]);
    assert_eq!(rules(&checked), ["record.edited"], "{}", checked.stdout);
}

/// A domain with one event (chunk 6.1c), as [`FILES`] is with routes.
const EVENT_FILES: &[(&str, &str)] = &[
    ("app.jadpo", "application {}\n"),
    (
        "domains/memos/types/memo_text.jadpo",
        "type MemoText = Text {\n    max_length: 200\n}\n",
    ),
    (
        "domains/memos/types/mood.jadpo",
        "type Mood = Enum {\n    calm\n    urgent\n}\n",
    ),
    (
        "domains/memos/events/memo_pinned.jadpo",
        "use memos/types { MemoText, Mood }\n\n/// A memo was pinned.\ntype MemoPinned = Event {\n    words: MemoText\n    mood: Mood\n    pinned_at: Instant\n}\n",
    ),
];

const EVENT_PATH: &str = "domains/memos/events/events.jadpo_record";

/// The event record `jadpo records update` writes for [`EVENT_FILES`].
const EVENT_RECORD: &str = "// Generated by Jadpo from the events of domain memos; update it with `jadpo records update`, never by hand.
record events 1

event MemoPinned
    mood: Mood
    pinned_at: Instant
    words: Text { max_length: 200 }

enum Mood
    variant calm
    variant urgent
";

fn event_project(stem: &str) -> (tempdir::Dir, PathBuf) {
    let dir = tempdir::Dir::new(stem);
    let root = dir.path().join("memos");
    for (path, text) in EVENT_FILES {
        write(&root, path, text);
    }
    (dir, root)
}

#[test]
fn records_update_writes_each_domains_event_record() {
    let (_dir, root) = event_project("records-events");
    let missing = jadpo(&root, &["check"]);
    assert_eq!(missing.code, 1);
    assert!(
        missing
            .stdout
            .contains("error: `domains/memos/events/events.jadpo_record` is missing\n"),
        "{}",
        missing.stdout
    );
    assert!(
        missing
            .stdout
            .contains("next: Run `jadpo records update`, and commit the record with the code"),
        "{}",
        missing.stdout
    );
    let updated = jadpo(&root, &["records", "update"]);
    assert_eq!(updated.code, 0, "{}", updated.stdout);
    assert_eq!(read(&root, EVENT_PATH), EVENT_RECORD);
    let checked = jadpo(&root, &["check"]);
    assert_eq!(checked.code, 0, "{}", checked.stdout);
    let listed = jadpo(&root, &["records"]);
    assert_eq!(listed.code, 0, "{}", listed.stdout);
    assert_eq!(
        listed.stdout,
        "jadpo records update
  domains/memos/events/events.jadpo_record  up to date

records up to date: 1 record
"
    );
}

#[test]
fn a_changed_event_shape_is_out_of_date_entry_by_entry() {
    let (_dir, root) = event_project("records-event-shape");
    write(&root, EVENT_PATH, EVENT_RECORD);
    // A field added to the event, and a variant to the enum it names.
    write(
        &root,
        "domains/memos/events/memo_pinned.jadpo",
        "use memos/types { MemoText, Mood }\n\n/// A memo was pinned.\ntype MemoPinned = Event {\n    words: MemoText\n    mood: Mood\n    pinned_at: Instant\n    by: MemoText\n}\n",
    );
    write(
        &root,
        "domains/memos/types/mood.jadpo",
        "type Mood = Enum {\n    calm\n    urgent\n    sleepy\n}\n",
    );
    let checked = jadpo(&root, &["check"]);
    assert_eq!(checked.code, 1);
    assert!(
        checked.stdout.contains(
            "error: `domains/memos/events/events.jadpo_record` is out of date\n --> domains/memos/events/events.jadpo_record:4:1\n"
        ),
        "{}",
        checked.stdout
    );
    assert!(
        checked.stdout.contains(
            "and the events now say otherwise: changed `event MemoPinned` and changed `enum Mood`."
        ),
        "{}",
        checked.stdout
    );
    let json = jadpo(&root, &["check", "--json"]);
    assert_eq!(rules(&json), ["record.out_of_date"], "{}", json.stdout);
    let rich = jadpo_in(
        Environment::empty()
            .with_terminals(true, true, true)
            .with_var("TERM", "xterm-256color")
            .with_var("NO_COLOR", "1"),
        &root,
        &["records"],
    );
    assert_eq!(rich.code, 1, "{}", rich.stdout);
    assert_eq!(
        strip_bold(&rich.stdout),
        "jadpo records update
✗ domains/memos/events/events.jadpo_record  out of date

✗ records out of date  1 out of date · 1 record

→ jadpo records update  brings domains/memos/events/events.jadpo_record up to date
"
    );
    assert_eq!(jadpo(&root, &["records", "update"]).code, 0);
    assert_eq!(
        read(&root, EVENT_PATH),
        EVENT_RECORD
            .replace(
                "event MemoPinned\n",
                "event MemoPinned\n    by: Text { max_length: 200 }\n"
            )
            .replace(
                "    variant calm\n",
                "    variant calm\n    variant sleepy\n"
            )
    );
    // A domain left with no events has its record removed.
    std::fs::remove_file(root.join("domains/memos/events/memo_pinned.jadpo")).expect("remove");
    let gone = jadpo(&root, &["check"]);
    assert!(
        gone.stdout
            .contains("error: `domains/memos/events/events.jadpo_record` records no events\n"),
        "{}",
        gone.stdout
    );
    assert_eq!(jadpo(&root, &["records", "update"]).code, 0);
    assert!(!root.join(EVENT_PATH).exists());
}

